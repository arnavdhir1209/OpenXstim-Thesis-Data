%% Stage2A_GradientThresholdRobustness.m
% OPENXSTIM GRADIENT-THRESHOLD ROBUSTNESS TEST
%
% Purpose
% -------
% Test whether the passive-versus-switching gradient separation found in
% Stage2A remains valid when the passive-edge exclusion guard is changed.
%
% Guards tested by default:
%
%       8 us, 10 us, 15 us, 20 us
%
% For every guard, current level and capture, the script:
%
%   1. uses the Stage 1 selected complete packet
%   2. reloads the original full-resolution CSV
%   3. derives command-guided switching edges using the already clean
%      low-current delay priors
%   4. defines each physical phase between successive switching edges
%   5. removes only GUARD_US from each end of the phase
%   6. measures the maximum passive |dI/dt| remaining in each phase
%   7. compares the upper passive distribution against the lower bipolar
%      switching-gradient distribution
%
% The key normalized statistic is:
%
%   normalized gradient = |dI/dt| / measured peak-to-peak current
%
% Main robustness question:
%
%   Does a positive gap remain for every tested guard and every current?
%
% If yes, the script also reports a conservative threshold interval:
%
%   lower safe bound = largest passive upper-tail value observed
%   upper safe bound = smallest bipolar-switch lower-tail value observed
%
% and a conservative midpoint threshold.
%
% Current convention
% ------------------
% Command current is PEAK TO PEAK.
%
% Measured current is also treated peak to peak:
%
%   Ipp = Ipositive - Inegative
%       = |Ipositive| + |Inegative|
%
% No Stage 1 or Stage 2 file is overwritten.

clear;
clc;
close all;

%% ========================================================================
% USER SETTINGS
% ========================================================================

cfg = struct();

cfg.DATA_ROOT = ...
    fileparts(mfilename("fullpath")); % Put the CSV files in the same folder as this script.

cfg.ANALYSIS_FOLDER = ...
    fullfile(cfg.DATA_ROOT,"Matlab Analysis");

cfg.STAGE1_MASTER_FILE = ...
    fullfile( ...
    cfg.ANALYSIS_FOLDER, ...
    "Stage1_PacketClassification", ...
    "Stage1MasterResults.mat");

cfg.STAGE2_MASTER_FILE = ...
    fullfile( ...
    cfg.ANALYSIS_FOLDER, ...
    "Stage2_CurrentResponseClassification", ...
    "Stage2MasterResults.mat");

cfg.OUTPUT_FOLDER = ...
    fullfile( ...
    cfg.ANALYSIS_FOLDER, ...
    "Stage2A_GradientThresholdRobustness");

cfg.OUTPUT_CHANNEL = 3;
cfg.R_LOAD_OHM = 1000;

% Keep the exact same CH3 smoothing used in Stage 2 / Stage2A V2.
cfg.OUTPUT_SMOOTH_US = 0.50;

% Guards to test.
cfg.GUARD_US_LIST = [8 10 15 20];

% Delay priors are estimated only from clean low-current PASS captures.
cfg.REFERENCE_MAX_COMMAND_CURRENT_mA = 10;

% Broad search around expected response centre.
% Search intervals are clipped halfway between neighbouring expected
% response centres so one command cannot steal the next command's edge.
cfg.GUIDED_SEARCH_HALF_WIDTH_US = 550;

% Local zero and selected packet response context.
cfg.ZERO_BASELINE_WINDOW_MS = 1.0;
cfg.ZERO_BASELINE_GUARD_US = 50;

cfg.RESPONSE_SEARCH_BEFORE_FIRST_COMMAND_MS = 0.10;
cfg.RESPONSE_SEARCH_AFTER_LAST_COMMAND_MS = 2.25;

% Robust p-p current estimate.
cfg.POSITIVE_LEVEL_PERCENTILE = 95;
cfg.NEGATIVE_LEVEL_PERCENTILE = 5;

% Separation statistics.
cfg.PASSIVE_PHASE_MAX_UPPER_PERCENTILE = 99;
cfg.BIPOLAR_SWITCH_LOWER_PERCENTILE = 1;

cfg.THRESHOLD_MIDPOINT_MODE = "arithmetic";

% Figures.
cfg.SAVE_PLOTS = true;
cfg.SHOW_FIGURES = false;
cfg.FIGURE_RESOLUTION_DPI = 180;

%% ========================================================================
% INPUT CHECKS
% ========================================================================

if ~isfile(cfg.STAGE1_MASTER_FILE)
    error("Stage 1 master file not found:\n%s",cfg.STAGE1_MASTER_FILE);
end

if ~isfile(cfg.STAGE2_MASTER_FILE)
    error("Stage 2 master file not found:\n%s",cfg.STAGE2_MASTER_FILE);
end

if ~isfolder(cfg.OUTPUT_FOLDER)
    mkdir(cfg.OUTPUT_FOLDER);
end

%% ========================================================================
% LOAD MASTER RESULTS
% ========================================================================

S1 = load(cfg.STAGE1_MASTER_FILE);
S2 = load(cfg.STAGE2_MASTER_FILE);

if ~isfield(S1,"CaptureSummary") || ~isfield(S1,"resultFiles")
    error("Stage 1 master file must contain CaptureSummary and resultFiles.");
end

if ~isfield(S2,"CaptureSummary") || ~isfield(S2,"PhysicalEvents")
    error("Stage 2 master file must contain CaptureSummary and PhysicalEvents.");
end

stage1Summary = S1.CaptureSummary;
stage1ResultFiles = string(S1.resultFiles);

stage2Summary = S2.CaptureSummary;
stage2PhysicalEvents = S2.PhysicalEvents;

%% ========================================================================
% DELAY PRIORS FROM CLEAN 5 / 10 mA CAPTURES
% ========================================================================

referenceCaptureIDs = ...
    stage2Summary.CaptureID( ...
    stage2Summary.Stage2Status=="PASS" & ...
    stage2Summary.CommandCurrent_mA<=cfg.REFERENCE_MAX_COMMAND_CURRENT_mA);

referenceEvents = ...
    stage2PhysicalEvents( ...
    ismember(stage2PhysicalEvents.CaptureID,referenceCaptureIDs) & ...
    startsWith(string(stage2PhysicalEvents.MatchStatus),"matched"),:);

classes = [ ...
    "zero_to_pos", ...
    "pos_to_neg", ...
    "neg_to_pos", ...
    "neg_to_zero"];

TransitionClass = classes(:);
NReferenceEvents = zeros(numel(classes),1);
MedianDelay_us = NaN(numel(classes),1);
RobustSD_us = NaN(numel(classes),1);
Q05_us = NaN(numel(classes),1);
Q95_us = NaN(numel(classes),1);

for k = 1:numel(classes)

    m = ...
        string(referenceEvents.CommandClass)==classes(k) & ...
        isfinite(referenceEvents.Delay_us);

    d = referenceEvents.Delay_us(m);

    NReferenceEvents(k) = numel(d);

    if ~isempty(d)

        MedianDelay_us(k) = median(d);
        RobustSD_us(k) = robustSigma(d);
        Q05_us(k) = percentileLocal(d,5);
        Q95_us(k) = percentileLocal(d,95);
    end
end

DelayPriors = table( ...
    TransitionClass, ...
    NReferenceEvents, ...
    MedianDelay_us, ...
    RobustSD_us, ...
    Q05_us, ...
    Q95_us);

if any(~isfinite(DelayPriors.MedianDelay_us))
    error("At least one transition class has no usable delay prior.");
end

fprintf("\n============================================================\n");
fprintf("OPENXSTIM GRADIENT-THRESHOLD ROBUSTNESS TEST\n");
fprintf("============================================================\n");

fprintf("Guards tested: ");
fprintf("%.0f us  ",cfg.GUARD_US_LIST);
fprintf("\n");

fprintf("\nDelay priors:\n");
disp(DelayPriors);

%% ========================================================================
% CONTAINERS
% ========================================================================

nCaptures = height(stage1Summary);
nGuards = numel(cfg.GUARD_US_LIST);

switchParts = cell(nCaptures,1);
scaleParts = cell(nCaptures,1);

% One cell for every capture x guard.
passiveParts = cell(nCaptures,nGuards);

%% ========================================================================
% PROCESS CAPTURES
%
% Switching edges are found ONCE per capture because the guard does not
% affect true-switch detection.
% ========================================================================

for c = 1:nCaptures

    captureID = stage1Summary.CaptureID(c);
    attemptNumber = stage1Summary.AttemptNumber(c);
    commandCurrent_mA = stage1Summary.CommandCurrent_mA(c);
    captureWithinAttempt = stage1Summary.CaptureWithinAttempt(c);

    fprintf("\n------------------------------------------------------------\n");
    fprintf("CAPTURE %d / %d | %.3g mA p-p\n", ...
        c,nCaptures,commandCurrent_mA);
    fprintf("------------------------------------------------------------\n");

    try

        if c>numel(stage1ResultFiles) || ...
                strlength(stage1ResultFiles(c))==0 || ...
                ~isfile(stage1ResultFiles(c))

            error("Stage 1 per-capture MAT file is missing.");
        end

        S = load(stage1ResultFiles(c));

        if ~isfield(S,"result")
            error("Stage 1 per-capture MAT contains no result.");
        end

        R1 = S.result;

        if ~isfield(R1,"selectedCommandTable") || ...
                isempty(R1.selectedCommandTable)

            error("No selected complete Stage 1 packet.");
        end

        commands = R1.selectedCommandTable;
        csvPath = string(R1.csvPath);

        if ~isfile(csvPath)
            error("Raw CSV not found: %s",csvPath);
        end

        [data,t,~,Ts,~] = loadRigolMemoryCSV(csvPath);

        Fs = 1/Ts;

        outputV = data(:,cfg.OUTPUT_CHANNEL);
        Iraw = 1000*outputV/cfg.R_LOAD_OHM;

        smoothSamples = ...
            max(3,round(cfg.OUTPUT_SMOOTH_US*1e-6/Ts));

        if mod(smoothSamples,2)==0
            smoothSamples = smoothSamples+1;
        end

        Ismooth = movmean(Iraw,smoothSamples);

        grad = gradient(Ismooth,Ts)/1e6;
        absGrad = abs(grad);

        commandTime_s = commands.CommandTime_s(:);
        commandClass = string(commands.TransitionClass(:));
        commandEvent = commands.EventNumberWithinPacket(:);

        nCommands = height(commands);

        %% ----------------------------------------------------------------
        % ZERO LEVEL
        % -----------------------------------------------------------------

        zeroEnd_s = ...
            commandTime_s(1)-cfg.ZERO_BASELINE_GUARD_US*1e-6;

        zeroStart_s = ...
            max( ...
            t(1), ...
            zeroEnd_s-cfg.ZERO_BASELINE_WINDOW_MS*1e-3);

        zeroMask = ...
            t>=zeroStart_s & ...
            t<=zeroEnd_s;

        if nnz(zeroMask)<20
            error("Insufficient local zero baseline.");
        end

        zeroLevel_mA = ...
            median(Iraw(zeroMask),'omitnan');

        %% ----------------------------------------------------------------
        % MEASURED PEAK-TO-PEAK CURRENT
        % -----------------------------------------------------------------

        responseStart_s = ...
            max( ...
            t(1), ...
            commandTime_s(1) ...
            - cfg.RESPONSE_SEARCH_BEFORE_FIRST_COMMAND_MS*1e-3);

        responseEnd_s = ...
            min( ...
            t(end), ...
            commandTime_s(end) ...
            + cfg.RESPONSE_SEARCH_AFTER_LAST_COMMAND_MS*1e-3);

        responseMask = ...
            t>=responseStart_s & ...
            t<=responseEnd_s;

        localI = Iraw(responseMask);

        positiveLevel_mA = ...
            percentileLocal( ...
            localI, ...
            cfg.POSITIVE_LEVEL_PERCENTILE);

        negativeLevel_mA = ...
            percentileLocal( ...
            localI, ...
            cfg.NEGATIVE_LEVEL_PERCENTILE);

        positiveHalf_mA = ...
            positiveLevel_mA-zeroLevel_mA;

        negativeHalf_mA = ...
            zeroLevel_mA-negativeLevel_mA;

        measuredIpp_mA = ...
            positiveLevel_mA-negativeLevel_mA;

        if ~isfinite(measuredIpp_mA) || measuredIpp_mA<=0
            error("Invalid measured p-p current.");
        end

        scaleParts{c} = table( ...
            captureID, ...
            attemptNumber, ...
            commandCurrent_mA, ...
            captureWithinAttempt, ...
            Fs/1e6, ...
            zeroLevel_mA, ...
            positiveLevel_mA, ...
            negativeLevel_mA, ...
            measuredIpp_mA, ...
            measuredIpp_mA/commandCurrent_mA, ...
            'VariableNames',{ ...
            'CaptureID', ...
            'AttemptNumber', ...
            'CommandCurrent_mA', ...
            'CaptureWithinAttempt', ...
            'Fs_MSa_s', ...
            'ZeroLevel_mA', ...
            'PositiveLevel_mA', ...
            'NegativeLevel_mA', ...
            'MeasuredIpp_mA', ...
            'MeasuredToCommandPPRatio'});

        %% ----------------------------------------------------------------
        % COMMAND-GUIDED SWITCHING EDGES
        % -----------------------------------------------------------------

        expectedCentre_s = NaN(nCommands,1);
        priorDelay_us = NaN(nCommands,1);
        expectedDirection = NaN(nCommands,1);

        for e = 1:nCommands

            p = find( ...
                DelayPriors.TransitionClass==commandClass(e), ...
                1);

            priorDelay_us(e) = ...
                DelayPriors.MedianDelay_us(p);

            expectedCentre_s(e) = ...
                commandTime_s(e) ...
                + priorDelay_us(e)*1e-6;

            expectedDirection(e) = ...
                transitionDirection(commandClass(e));
        end

        responseTime_s = NaN(nCommands,1);
        measuredDelay_us = NaN(nCommands,1);
        signedGradient_mA_per_us = NaN(nCommands,1);
        absGradient_mA_per_us = NaN(nCommands,1);
        expectedPhysicalStep_mA = NaN(nCommands,1);
        normGradientByIpp_per_us = NaN(nCommands,1);
        normGradientByExpectedStep_per_us = NaN(nCommands,1);

        for e = 1:nCommands

            lo = ...
                expectedCentre_s(e) ...
                - cfg.GUIDED_SEARCH_HALF_WIDTH_US*1e-6;

            hi = ...
                expectedCentre_s(e) ...
                + cfg.GUIDED_SEARCH_HALF_WIDTH_US*1e-6;

            if e>1

                lo = max( ...
                    lo, ...
                    0.5*( ...
                    expectedCentre_s(e-1) ...
                    + expectedCentre_s(e)));
            end

            if e<nCommands

                hi = min( ...
                    hi, ...
                    0.5*( ...
                    expectedCentre_s(e) ...
                    + expectedCentre_s(e+1)));
            end

            lo = max(lo,responseStart_s);
            hi = min(hi,responseEnd_s);

            m = ...
                t>=lo & ...
                t<=hi & ...
                sign(grad)==expectedDirection(e);

            idx = find(m);

            if isempty(idx)
                continue;
            end

            [~,ii] = max(absGrad(idx));

            edgeIdx = idx(ii);

            responseTime_s(e) = t(edgeIdx);

            measuredDelay_us(e) = ...
                (responseTime_s(e)-commandTime_s(e))*1e6;

            signedGradient_mA_per_us(e) = grad(edgeIdx);
            absGradient_mA_per_us(e) = absGrad(edgeIdx);

            expectedPhysicalStep_mA(e) = ...
                expectedPhysicalStep( ...
                commandClass(e), ...
                positiveHalf_mA, ...
                negativeHalf_mA, ...
                measuredIpp_mA);

            normGradientByIpp_per_us(e) = ...
                absGradient_mA_per_us(e)/measuredIpp_mA;

            normGradientByExpectedStep_per_us(e) = ...
                absGradient_mA_per_us(e) ...
                / expectedPhysicalStep_mA(e);
        end

        validEdges = isfinite(responseTime_s);

        fprintf("Measured Ipp            : %.6f mA\n",measuredIpp_mA);
        fprintf("Guided switch edges     : %d / %d\n", ...
            nnz(validEdges),nCommands);

        if nnz(validEdges)~=nCommands

            warning( ...
                "Capture %d only found %d / %d guided edges.", ...
                captureID,nnz(validEdges),nCommands);
        end

        isBipolar = ...
            commandClass=="pos_to_neg" | ...
            commandClass=="neg_to_pos";

        SwitchEdgesThisCapture = table( ...
            repmat(captureID,nCommands,1), ...
            repmat(attemptNumber,nCommands,1), ...
            repmat(commandCurrent_mA,nCommands,1), ...
            repmat(captureWithinAttempt,nCommands,1), ...
            commandEvent, ...
            commandClass, ...
            isBipolar, ...
            commandTime_s, ...
            priorDelay_us, ...
            responseTime_s, ...
            measuredDelay_us, ...
            expectedDirection, ...
            signedGradient_mA_per_us, ...
            absGradient_mA_per_us, ...
            repmat(measuredIpp_mA,nCommands,1), ...
            expectedPhysicalStep_mA, ...
            normGradientByIpp_per_us, ...
            normGradientByExpectedStep_per_us, ...
            'VariableNames',{ ...
            'CaptureID', ...
            'AttemptNumber', ...
            'CommandCurrent_mA', ...
            'CaptureWithinAttempt', ...
            'CommandEvent', ...
            'TransitionClass', ...
            'IsBipolar', ...
            'CommandTime_s', ...
            'ReferenceDelay_us', ...
            'GuidedResponseTime_s', ...
            'GuidedDelay_us', ...
            'ExpectedGradientDirection', ...
            'SignedGradient_mA_per_us', ...
            'AbsGradient_mA_per_us', ...
            'MeasuredIpp_mA', ...
            'ExpectedPhysicalStep_mA', ...
            'NormGradientByIpp_per_us', ...
            'NormGradientByExpectedStep_per_us'});

        switchParts{c} = SwitchEdgesThisCapture;

        %% ----------------------------------------------------------------
        % PASSIVE PHASE MAXIMA FOR EACH GUARD
        % -----------------------------------------------------------------

        if nnz(validEdges)<2
            continue;
        end

        for g = 1:nGuards

            guard_us = cfg.GUARD_US_LIST(g);
            guard_s = guard_us*1e-6;

            phaseRows = cell(nCommands-1,1);

            for p = 1:nCommands-1

                if ~isfinite(responseTime_s(p)) || ...
                        ~isfinite(responseTime_s(p+1))

                    continue;
                end

                phaseStart_s = responseTime_s(p);
                phaseEnd_s = responseTime_s(p+1);

                passiveStart_s = phaseStart_s+guard_s;
                passiveEnd_s = phaseEnd_s-guard_s;

                if passiveEnd_s<=passiveStart_s
                    continue;
                end

                m = ...
                    t>=passiveStart_s & ...
                    t<=passiveEnd_s;

                idx = find(m);

                if numel(idx)<10
                    continue;
                end

                passiveAbs = absGrad(idx);

                [phaseMaxRaw,ii] = max(passiveAbs);

                phaseMaxTime_s = t(idx(ii));

                phaseRows{p} = table( ...
                    captureID, ...
                    attemptNumber, ...
                    commandCurrent_mA, ...
                    captureWithinAttempt, ...
                    guard_us, ...
                    p, ...
                    commandClass(p), ...
                    commandClass(p+1), ...
                    phaseStart_s, ...
                    phaseEnd_s, ...
                    passiveStart_s, ...
                    passiveEnd_s, ...
                    phaseMaxTime_s, ...
                    phaseMaxRaw, ...
                    phaseMaxRaw/measuredIpp_mA, ...
                    measuredIpp_mA, ...
                    'VariableNames',{ ...
                    'CaptureID', ...
                    'AttemptNumber', ...
                    'CommandCurrent_mA', ...
                    'CaptureWithinAttempt', ...
                    'Guard_us', ...
                    'PhysicalPhase', ...
                    'StartTransitionClass', ...
                    'EndTransitionClass', ...
                    'PhaseStart_s', ...
                    'PhaseEnd_s', ...
                    'PassiveStart_s', ...
                    'PassiveEnd_s', ...
                    'PassiveMaxTime_s', ...
                    'PassiveMaxAbsGradient_mA_per_us', ...
                    'PassiveMaxNormByIpp_per_us', ...
                    'MeasuredIpp_mA'});
            end

            phaseRows = ...
                phaseRows(~cellfun(@isempty,phaseRows));

            if ~isempty(phaseRows)

                passiveParts{c,g} = ...
                    vertcat(phaseRows{:});

                fprintf( ...
                    "Guard %2.0f us | phases %2d | max passive %.6f mA/us\n", ...
                    guard_us, ...
                    height(passiveParts{c,g}), ...
                    max( ...
                    passiveParts{c,g}.PassiveMaxAbsGradient_mA_per_us, ...
                    [], ...
                    'omitnan'));
            end
        end

        clear data t outputV Iraw Ismooth grad absGrad

    catch ME

        fprintf(2,"Capture %d failed: %s\n",captureID,ME.message);
    end
end

%% ========================================================================
% COMBINE TABLES
% ========================================================================

switchParts = switchParts(~cellfun(@isempty,switchParts));

if isempty(switchParts)
    SwitchEdges = table();
else
    SwitchEdges = vertcat(switchParts{:});
end

scaleParts = scaleParts(~cellfun(@isempty,scaleParts));

if isempty(scaleParts)
    CaptureCurrentScale = table();
else
    CaptureCurrentScale = vertcat(scaleParts{:});
end

allPassiveParts = passiveParts(~cellfun(@isempty,passiveParts));

if isempty(allPassiveParts)
    PassivePhaseMaxima = table();
else
    PassivePhaseMaxima = vertcat(allPassiveParts{:});
end

if isempty(SwitchEdges) || isempty(PassivePhaseMaxima)
    error("Switch-edge or passive-phase dataset is empty.");
end

%% ========================================================================
% SAVE INTERMEDIATE DATA BEFORE STATISTICS / PLOTS
% ========================================================================

writetable( ...
    DelayPriors, ...
    fullfile(cfg.OUTPUT_FOLDER,"DelayReferenceByClass.csv"));

writetable( ...
    CaptureCurrentScale, ...
    fullfile(cfg.OUTPUT_FOLDER,"MeasuredPeakToPeakCurrentByCapture.csv"));

writetable( ...
    SwitchEdges, ...
    fullfile(cfg.OUTPUT_FOLDER,"GuidedSwitchEdges.csv"));

writetable( ...
    PassivePhaseMaxima, ...
    fullfile(cfg.OUTPUT_FOLDER,"PassivePhaseMaxima_AllGuards.csv"));

save( ...
    fullfile(cfg.OUTPUT_FOLDER,"Stage2A_RobustnessIntermediate.mat"), ...
    "DelayPriors", ...
    "CaptureCurrentScale", ...
    "SwitchEdges", ...
    "PassivePhaseMaxima", ...
    "cfg", ...
    "-v7.3");

%% ========================================================================
% BY-GUARD, BY-CURRENT SEPARATION TABLE
% ========================================================================

currents = unique(CaptureCurrentScale.CommandCurrent_mA);

rows = cell(nGuards*numel(currents),1);

r = 0;

for g = 1:nGuards

    guard_us = cfg.GUARD_US_LIST(g);

    for k = 1:numel(currents)

        r = r+1;

        Icmd = currents(k);

        pm = ...
            PassivePhaseMaxima.Guard_us==guard_us & ...
            PassivePhaseMaxima.CommandCurrent_mA==Icmd;

        sm = ...
            SwitchEdges.CommandCurrent_mA==Icmd & ...
            SwitchEdges.IsBipolar & ...
            isfinite(SwitchEdges.AbsGradient_mA_per_us);

        passiveRaw = ...
            PassivePhaseMaxima.PassiveMaxAbsGradient_mA_per_us(pm);

        passiveNorm = ...
            PassivePhaseMaxima.PassiveMaxNormByIpp_per_us(pm);

        switchRaw = ...
            SwitchEdges.AbsGradient_mA_per_us(sm);

        switchNorm = ...
            SwitchEdges.NormGradientByIpp_per_us(sm);

        passiveUpperRaw = ...
            percentileLocal( ...
            passiveRaw, ...
            cfg.PASSIVE_PHASE_MAX_UPPER_PERCENTILE);

        switchLowerRaw = ...
            percentileLocal( ...
            switchRaw, ...
            cfg.BIPOLAR_SWITCH_LOWER_PERCENTILE);

        rawGap = ...
            switchLowerRaw-passiveUpperRaw;

        passiveUpperNorm = ...
            percentileLocal( ...
            passiveNorm, ...
            cfg.PASSIVE_PHASE_MAX_UPPER_PERCENTILE);

        switchLowerNorm = ...
            percentileLocal( ...
            switchNorm, ...
            cfg.BIPOLAR_SWITCH_LOWER_PERCENTILE);

        normGap = ...
            switchLowerNorm-passiveUpperNorm;

        if rawGap>0

            rawThreshold = ...
                thresholdMidpoint( ...
                passiveUpperRaw, ...
                switchLowerRaw, ...
                cfg.THRESHOLD_MIDPOINT_MODE);

        else

            rawThreshold = NaN;
        end

        if normGap>0

            normThreshold = ...
                thresholdMidpoint( ...
                passiveUpperNorm, ...
                switchLowerNorm, ...
                cfg.THRESHOLD_MIDPOINT_MODE);

        else

            normThreshold = NaN;
        end

        measuredIpp = ...
            CaptureCurrentScale.MeasuredIpp_mA( ...
            CaptureCurrentScale.CommandCurrent_mA==Icmd);

        rows{r} = table( ...
            guard_us, ...
            Icmd, ...
            nnz(pm), ...
            mean(measuredIpp,'omitnan'), ...
            passiveUpperRaw, ...
            switchLowerRaw, ...
            rawGap, ...
            switchLowerRaw/passiveUpperRaw, ...
            rawThreshold, ...
            passiveUpperNorm, ...
            switchLowerNorm, ...
            normGap, ...
            switchLowerNorm/passiveUpperNorm, ...
            normThreshold, ...
            'VariableNames',{ ...
            'Guard_us', ...
            'CommandCurrent_mA', ...
            'NPassivePhases', ...
            'MeanMeasuredIpp_mA', ...
            'PassiveUpperRaw_mA_per_us', ...
            'BipolarSwitchLowerRaw_mA_per_us', ...
            'RawGap_mA_per_us', ...
            'RawGapRatio', ...
            'SuggestedRawThreshold_mA_per_us', ...
            'PassiveUpperNorm_per_us', ...
            'BipolarSwitchLowerNorm_per_us', ...
            'NormalizedGap_per_us', ...
            'NormalizedGapRatio', ...
            'SuggestedNormalizedThreshold_per_us'});
    end
end

RobustnessByCurrent = vertcat(rows{:});

%% ========================================================================
% GLOBAL ROBUSTNESS BY GUARD
% ========================================================================

globalRows = cell(nGuards,1);

for g = 1:nGuards

    guard_us = cfg.GUARD_US_LIST(g);

    pm = ...
        PassivePhaseMaxima.Guard_us==guard_us;

    sm = ...
        SwitchEdges.IsBipolar & ...
        isfinite(SwitchEdges.NormGradientByIpp_per_us);

    passiveNorm = ...
        PassivePhaseMaxima.PassiveMaxNormByIpp_per_us(pm);

    switchNorm = ...
        SwitchEdges.NormGradientByIpp_per_us(sm);

    passiveUpperNorm = ...
        percentileLocal( ...
        passiveNorm, ...
        cfg.PASSIVE_PHASE_MAX_UPPER_PERCENTILE);

    switchLowerNorm = ...
        percentileLocal( ...
        switchNorm, ...
        cfg.BIPOLAR_SWITCH_LOWER_PERCENTILE);

    gap = ...
        switchLowerNorm-passiveUpperNorm;

    if gap>0

        suggested = ...
            thresholdMidpoint( ...
            passiveUpperNorm, ...
            switchLowerNorm, ...
            cfg.THRESHOLD_MIDPOINT_MODE);

    else

        suggested = NaN;
    end

