function plotPhaseClassificationAxis( ...
    ax,t,currentRaw_mA,PhysicalEvents,PhysicalPhases, ...
    xRange_s,showLabels,showLegend,cfg)

    if isempty(xRange_s)

        eventTimes = [ ...
            PhysicalEvents.CommandTime_s; ...
            PhysicalEvents.ResponseTime_s];

        eventTimes = eventTimes(isfinite(eventTimes));

        if isempty(eventTimes)
            xRange_s = [t(1) t(end)];
        else
            xRange_s = [ ...
                max(t(1),min(eventTimes)-0.35e-3), ...
                min(t(end),max(eventTimes)+0.35e-3)];
        end
    end

    xMin_s = xRange_s(1);
    xMax_s = xRange_s(2);

    plotMask = ...
        t>=xMin_s & ...
        t<=xMax_s;

    idx = find(plotMask);

    if isempty(idx)
        return;
    end

    stride = ...
        max(1,ceil(numel(idx)/cfg.MAX_PLOT_POINTS));

    idx = idx(1:stride:end);

    yVisible = currentRaw_mA(plotMask);
    yVisible = yVisible(isfinite(yVisible));

    if isempty(yVisible)
        yMin = -1;
        yMax = 1;
    else
        yMin = min(yVisible);
        yMax = max(yVisible);
    end

    ySpan = yMax-yMin;

    if ~isfinite(ySpan) || ySpan<=0
        ySpan = 1;
    end

    yMin = yMin-0.06*ySpan;
    yMax = yMax+0.06*ySpan;

    co = get(groot,'defaultAxesColorOrder');

    positiveColor = co(1,:);
    negativeColor = co(2,:);
    observedColor = [0.12 0.12 0.12];
    surrogateColor = [0.45 0.20 0.55];
    commandColor = [0.55 0.55 0.55];

    hold(ax,'on');

    positiveLegendDone = false;
    negativeLegendDone = false;

    % ------------------------------------------------------------------
    % Shade only the region classified as passive droop / current loss.
    % The short unshaded gaps around each response are the fast-transition
    % exclusion guards.
    % ------------------------------------------------------------------

    for p = 1:height(PhysicalPhases)

        a = max(PhysicalPhases.PassiveStart_s(p),xMin_s);
        b = min(PhysicalPhases.PassiveEnd_s(p),xMax_s);

        if ~isfinite(a) || ~isfinite(b) || b<=a
            continue;
        end

        if PhysicalPhases.Polarity(p)=="positive"

            c = positiveColor;

            if ~positiveLegendDone

                patch( ...
                    ax, ...
                    [a b b a]*1e3, ...
                    [yMin yMin yMax yMax], ...
                    c, ...
                    'FaceAlpha',0.08, ...
                    'EdgeColor','none', ...
                    'DisplayName','Positive passive region');

                positiveLegendDone = true;

            else

                patch( ...
                    ax, ...
                    [a b b a]*1e3, ...
                    [yMin yMin yMax yMax], ...
                    c, ...
                    'FaceAlpha',0.08, ...
                    'EdgeColor','none', ...
                    'HandleVisibility','off');
            end

        else

            c = negativeColor;

            if ~negativeLegendDone

                patch( ...
                    ax, ...
                    [a b b a]*1e3, ...
                    [yMin yMin yMax yMax], ...
                    c, ...
                    'FaceAlpha',0.08, ...
                    'EdgeColor','none', ...
                    'DisplayName','Negative passive region');

                negativeLegendDone = true;

            else

                patch( ...
                    ax, ...
                    [a b b a]*1e3, ...
                    [yMin yMin yMax yMax], ...
                    c, ...
                    'FaceAlpha',0.08, ...
                    'EdgeColor','none', ...
                    'HandleVisibility','off');
            end
        end

        if showLabels

            xMid_ms = 0.5*(a+b)*1e3;

            if PhysicalPhases.Polarity(p)=="positive"
                yText = yMax-0.08*(yMax-yMin);
                signText = '+';
            else
                yText = yMin+0.08*(yMax-yMin);
                signText = '-';
            end

            text( ...
                ax, ...
                xMid_ms, ...
                yText, ...
                sprintf('P%d %s droop', ...
                PhysicalPhases.PulseNumber(p),signText), ...
                'HorizontalAlignment','center', ...
                'FontSize',8, ...
                'Clipping','on');
        end
    end

    % Raw current on top of the phase shading.
    plot( ...
        ax, ...
        t(idx)*1e3, ...
        currentRaw_mA(idx), ...
        'LineWidth',0.8, ...
        'DisplayName','CH3');

    % Dummy legend handles for line semantics.
    plot(ax,nan,nan,':','Color',commandColor, ...
        'LineWidth',0.9,'DisplayName','Stage 1 command time');

    plot(ax,nan,nan,'-','Color',observedColor, ...
        'LineWidth',1.1,'DisplayName','Observed physical transition');

    plot(ax,nan,nan,'--','Color',surrogateColor, ...
        'LineWidth',1.1,'DisplayName','Timing-surrogate boundary');

    if showLabels

        plot(ax,nan,nan,'-','Color',[0.25 0.25 0.25], ...
            'LineWidth',2.4,'DisplayName','Early level window');

        plot(ax,nan,nan,'--','Color',[0.25 0.25 0.25], ...
            'LineWidth',2.0,'DisplayName','Late level window');
    end

    % ------------------------------------------------------------------
    % Mark command times and corresponding classified responses.
    % ------------------------------------------------------------------

    for e = 1:height(PhysicalEvents)

        cmdTime = PhysicalEvents.CommandTime_s(e);

        if isfinite(cmdTime) && cmdTime>=xMin_s && cmdTime<=xMax_s

            if showLabels
                cmdLabel = sprintf('C%d',PhysicalEvents.CommandEvent(e));
            else
                cmdLabel = '';
            end

            xline( ...
                ax, ...
                cmdTime*1e3, ...
                ':', ...
                cmdLabel, ...
                'Color',commandColor, ...
                'LineWidth',0.8, ...
                'HandleVisibility','off', ...
                'LabelOrientation','aligned');
        end

        responseTime = PhysicalEvents.ResponseTime_s(e);

        if ~PhysicalEvents.AcceptedResponse(e) || ...
                ~isfinite(responseTime) || ...
                responseTime<xMin_s || ...
                responseTime>xMax_s

            continue;
        end

        if PhysicalEvents.PhysicalEdgeObserved(e)

            lineStyle = '-';
            lineColor = observedColor;
            marker = 'o';
            sourceTag = '';

        else

            lineStyle = '--';
            lineColor = surrogateColor;
            marker = 's';
            sourceTag = ' [timing]';
        end

        if showLabels

            responseLabel = sprintf( ...
                'R%d %s%s', ...
                PhysicalEvents.CommandEvent(e), ...
                prettyTransition(PhysicalEvents.CommandClass(e)), ...
                sourceTag);

        else

            responseLabel = '';
        end

        xline( ...
            ax, ...
            responseTime*1e3, ...
            lineStyle, ...
            responseLabel, ...
            'Color',lineColor, ...
            'LineWidth',1.0, ...
            'HandleVisibility','off', ...
            'LabelOrientation','aligned');

        yResponse = interp1( ...
            t,currentRaw_mA,responseTime, ...
            'linear',NaN);

        scatter( ...
            ax, ...
            responseTime*1e3, ...
            yResponse, ...
            26, ...
            lineColor, ...
            marker, ...
            'filled', ...
            'HandleVisibility','off');
    end

    % ------------------------------------------------------------------
    % Draw the actual early / late windows used for droop quantification.
    % ------------------------------------------------------------------

    if showLabels

        for p = 1:height(PhysicalPhases)

            if PhysicalPhases.Polarity(p)=="positive"
                c = positiveColor;
            else
                c = negativeColor;
            end

            ea = PhysicalPhases.EarlyWindowStart_s(p);
            eb = PhysicalPhases.EarlyWindowEnd_s(p);
            la = PhysicalPhases.LateWindowStart_s(p);
            lb = PhysicalPhases.LateWindowEnd_s(p);

            if isfinite(ea) && isfinite(eb) && ...
                    eb>=xMin_s && ea<=xMax_s

                plot( ...
                    ax, ...
                    [max(ea,xMin_s) min(eb,xMax_s)]*1e3, ...
                    [PhysicalPhases.EarlyCurrent_mA(p) ...
                    PhysicalPhases.EarlyCurrent_mA(p)], ...
                    '-', ...
                    'Color',c, ...
                    'LineWidth',2.6, ...
                    'HandleVisibility','off');
            end

            if isfinite(la) && isfinite(lb) && ...
                    lb>=xMin_s && la<=xMax_s

                plot( ...
                    ax, ...
                    [max(la,xMin_s) min(lb,xMax_s)]*1e3, ...
                    [PhysicalPhases.LateCurrent_mA(p) ...
                    PhysicalPhases.LateCurrent_mA(p)], ...
                    '--', ...
                    'Color',c, ...
                    'LineWidth',2.2, ...
                    'HandleVisibility','off');
            end
        end
    end

    xlim(ax,[xMin_s xMax_s]*1e3);
    ylim(ax,[yMin yMax]);

    grid(ax,'on');

    xlabel(ax,'Time (ms)');
    ylabel(ax,'Measured current (mA)');

    if showLegend
        legend(ax,'Location','best');
    end

    hold(ax,'off');
end

function [figOverview,figZoom] = makeMasterPhaseClassificationFigures( ...
    CaptureSummary,stage1Summary,resultFiles,cfg)

    valid = ...
        CaptureSummary.Stage2Status=="PASS" & ...
        isfinite(CaptureSummary.MeanEarlyMeasuredIpp_mA);

    currents = ...
        unique(CaptureSummary.CommandCurrent_mA(valid));

    vis = onOff(cfg.SHOW_MASTER_FIGURES);

    figOverview = figure( ...
        'Visible',vis, ...
        'Color','w', ...
        'Position',[40 40 1550 1200]);

    tlFull = tiledlayout( ...
        figOverview,3,2, ...
        'TileSpacing','compact', ...
        'Padding','compact');

    title(tlFull, ...
        'Stage 2 passive-phase classification overview | representative capture at each current');

    figZoom = figure( ...
        'Visible',vis, ...
        'Color','w', ...
        'Position',[55 55 1550 1200]);

    tlZoom = tiledlayout( ...
        figZoom,3,2, ...
        'TileSpacing','compact', ...
        'Padding','compact');

    title(tlZoom,sprintf( ...
        'Stage 2 command / transition / droop classification | first %d pulses', ...
        cfg.CLASSIFICATION_ZOOM_PULSES));

    for k = 1:numel(currents)

        Icmd = currents(k);

        rows = find( ...
            valid & ...
            CaptureSummary.CommandCurrent_mA==Icmd);

        if isempty(rows)
            nexttile(tlFull);
            nexttile(tlZoom);
            continue;
        end

        target = ...
            mean( ...
            CaptureSummary.MeanEarlyMeasuredIpp_mA(rows), ...
            'omitnan');

        [~,ii] = min(abs( ...
            CaptureSummary.MeanEarlyMeasuredIpp_mA(rows)-target));

        row = rows(ii);
        captureID = CaptureSummary.CaptureID(row);

        sourceIndex = find( ...
            stage1Summary.CaptureID==captureID,1);

        if isempty(sourceIndex) || ...
                sourceIndex>numel(resultFiles) || ...
                strlength(resultFiles(sourceIndex))==0 || ...
                ~isfile(resultFiles(sourceIndex))

            nexttile(tlFull);
            nexttile(tlZoom);
            continue;
        end

        S = load(resultFiles(sourceIndex));

        if ~isfield(S,'results')
            nexttile(tlFull);
            nexttile(tlZoom);
            continue;
        end

        R = S.results;

        [data,t,~,~,~] = ...
            loadRigolMemoryCSV(R.csvPath);

        outputV = data(:,cfg.OUTPUT_CHANNEL);
        Iraw = 1000*outputV/cfg.R_LOAD_OHM;

        axFull = nexttile(tlFull);

        plotPhaseClassificationAxis( ...
            axFull,t,Iraw,R.physicalEvents,R.physicalPhases, ...
            [],false,k==1,cfg);

        title(axFull,sprintf( ...
            '%.3g mA p-p | Capture %03d | full packet', ...
            Icmd,captureID));

        nEvents = height(R.physicalEvents);

        zoomLastEvent = ...
            min(2*cfg.CLASSIFICATION_ZOOM_PULSES+1,nEvents);

        zoomTimes = [ ...
            R.physicalEvents.CommandTime_s(1:zoomLastEvent); ...
            R.physicalEvents.ResponseTime_s(1:zoomLastEvent)];

        zoomTimes = zoomTimes(isfinite(zoomTimes));

        if isempty(zoomTimes)
            zoomRange_s = [];
        else
            zoomRange_s = [ ...
                max(t(1),min(zoomTimes)-0.25e-3), ...
                min(t(end),max(zoomTimes)+0.25e-3)];
        end

        axZoom = nexttile(tlZoom);

        plotPhaseClassificationAxis( ...
            axZoom,t,Iraw,R.physicalEvents,R.physicalPhases, ...
            zoomRange_s,true,k==1,cfg);

        title(axZoom,sprintf( ...
            '%.3g mA p-p | Capture %03d | labelled commands and responses', ...
            Icmd,captureID));

        clear data t outputV Iraw
    end
end

function T = buildCurrentLevelSummary(CaptureSummary)

    if isempty(CaptureSummary)

        T = table();
        return;
    end

    valid = ...
        CaptureSummary.Stage2Status~="FAIL" & ...
        isfinite(CaptureSummary.CommandCurrent_mA) & ...
        isfinite(CaptureSummary.MeanEarlyMeasuredIpp_mA);

    C = ...
        CaptureSummary(valid,:);

    if isempty(C)

        T = table();
        return;
    end

    currents = ...
        unique(C.CommandCurrent_mA);

    n = ...
        numel(currents);

    CommandCurrent_mA = currents;
    NCaptures = zeros(n,1);

    MeanEarlyMeasuredIpp_mA = NaN(n,1);
    SDAcrossCapturesEarlyMeasuredIpp_mA = NaN(n,1);

    MeanLateMeasuredIpp_mA = NaN(n,1);

    MeanMeasuredToCommandRatio = NaN(n,1);
    SDMeasuredToCommandRatio = NaN(n,1);

    MeanPeakToPeakDroop_mA = NaN(n,1);
    MeanPeakToPeakDroopFraction = NaN(n,1);

    MeanPosToNegDelay_us = NaN(n,1);
    SDPosToNegDelayAcrossCaptures_us = NaN(n,1);

    MeanNegToPosDelay_us = NaN(n,1);
    SDNegToPosDelayAcrossCaptures_us = NaN(n,1);

    for k = 1:n

        m = ...
            C.CommandCurrent_mA==currents(k);

        NCaptures(k) = ...
            nnz(m);

        MeanEarlyMeasuredIpp_mA(k) = ...
            mean(C.MeanEarlyMeasuredIpp_mA(m),'omitnan');

        SDAcrossCapturesEarlyMeasuredIpp_mA(k) = ...
            std(C.MeanEarlyMeasuredIpp_mA(m),'omitnan');

        MeanLateMeasuredIpp_mA(k) = ...
            mean(C.MeanLateMeasuredIpp_mA(m),'omitnan');

        MeanMeasuredToCommandRatio(k) = ...
            mean(C.MeanMeasuredToCommandRatio(m),'omitnan');

        SDMeasuredToCommandRatio(k) = ...
            std(C.MeanMeasuredToCommandRatio(m),'omitnan');

        MeanPeakToPeakDroop_mA(k) = ...
            mean(C.MeanPeakToPeakDroop_mA(m),'omitnan');

        MeanPeakToPeakDroopFraction(k) = ...
            mean(C.MeanPeakToPeakDroopFraction(m),'omitnan');

        MeanPosToNegDelay_us(k) = ...
            mean(C.MeanPosToNegDelay_us(m),'omitnan');

        SDPosToNegDelayAcrossCaptures_us(k) = ...
            std(C.MeanPosToNegDelay_us(m),'omitnan');

        MeanNegToPosDelay_us(k) = ...
            mean(C.MeanNegToPosDelay_us(m),'omitnan');

        SDNegToPosDelayAcrossCaptures_us(k) = ...
            std(C.MeanNegToPosDelay_us(m),'omitnan');
    end

    T = table( ...
        CommandCurrent_mA, ...
        NCaptures, ...
        MeanEarlyMeasuredIpp_mA, ...
        SDAcrossCapturesEarlyMeasuredIpp_mA, ...
        MeanLateMeasuredIpp_mA, ...
        MeanMeasuredToCommandRatio, ...
        SDMeasuredToCommandRatio, ...
        MeanPeakToPeakDroop_mA, ...
        MeanPeakToPeakDroopFraction, ...
        MeanPosToNegDelay_us, ...
        SDPosToNegDelayAcrossCaptures_us, ...
        MeanNegToPosDelay_us, ...
        SDNegToPosDelayAcrossCaptures_us);
end

