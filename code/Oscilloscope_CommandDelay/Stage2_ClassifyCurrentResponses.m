            magnitudeSlope_mA_per_ms = magnitudeFit(1);

            yhat = ...
                polyval(signedFit,phaseTime_ms);

            denom = ...
                sum( ...
                (phaseCurrentSmooth_mA ...
                - mean(phaseCurrentSmooth_mA,'omitnan')).^2);

            if denom>0

                linearFitR2 = ...
                    1 ...
                    - sum((phaseCurrentSmooth_mA-yhat).^2)/denom;

            else

                linearFitR2 = NaN;
            end

            earlyEnd_s = ...
                min( ...
                passiveStart_s+levelWindow_s, ...
                passiveEnd_s);

            lateStart_s = ...
                max( ...
                passiveEnd_s-levelWindow_s, ...
                passiveStart_s);

            earlyMask = ...
                t>=passiveStart_s & ...
                t<=earlyEnd_s;

