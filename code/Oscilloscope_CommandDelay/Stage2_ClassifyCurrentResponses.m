                lateCurrent_mA, ...
                earlyMagnitude_mA, ...
                lateMagnitude_mA, ...
                magnitudeDroop_mA, ...
                droopFraction, ...
                signedSlope_mA_per_ms, ...
                magnitudeSlope_mA_per_ms, ...
                linearFitR2, ...
                'VariableNames',{ ...
                'CaptureID', ...
                'AttemptNumber', ...
                'CommandCurrent_mA', ...
                'CaptureWithinAttempt', ...
                'PhysicalPhase', ...
                'PulseNumber', ...
                'Polarity', ...
                'PhaseClass', ...
                'StartTransitionClass', ...
                'EndTransitionClass', ...
                'FastStart_s', ...
                'FastEnd_s', ...
                'PassiveStart_s', ...
                'PassiveEnd_s', ...
                'EarlyWindowStart_s', ...
                'EarlyWindowEnd_s', ...
                'LateWindowStart_s', ...
                'LateWindowEnd_s', ...
                'FullPhaseDuration_us', ...
                'PassiveAnalysisDuration_us', ...
                'EarlyCurrent_mA', ...
                'LateCurrent_mA', ...
                'EarlyMagnitude_mA', ...
                'LateMagnitude_mA', ...
                'MagnitudeDroop_mA', ...
                'DroopFraction', ...
                'SignedSlope_mA_per_ms', ...
                'MagnitudeSlope_mA_per_ms', ...
                'LinearFitR2'});
        end

