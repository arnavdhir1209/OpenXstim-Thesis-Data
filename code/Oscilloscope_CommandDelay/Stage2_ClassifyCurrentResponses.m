                phasePulseNumber = pulseNumber(e);

            elseif sourceClass=="pos_to_neg" && ...
                    (nextClass=="neg_to_pos" || ...
                    nextClass=="neg_to_zero")

                polarity = "negative";
                phasePulseNumber = pulseNumber(e);

            else

                continue;
            end

            phaseCounter = phaseCounter+1;

            fastStart_s = responseTime_s(e);
            fastEnd_s = responseTime_s(e+1);

            passiveStart_s = fastStart_s+guard_s;
            passiveEnd_s = fastEnd_s-guard_s;

            if passiveEnd_s<=passiveStart_s
                continue;
            end

            phaseMask = ...
                t>=passiveStart_s & ...
                t<=passiveEnd_s;

