                'CommandCurrent_mA', ...
                'CaptureWithinAttempt', ...
                'PulseNumber', ...
                'PositiveEarlyCurrent_mA', ...
                'NegativeEarlyCurrent_mA', ...
                'PositiveLateCurrent_mA', ...
