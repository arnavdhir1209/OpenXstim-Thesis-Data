function label = prettyTransition(type)

    switch string(type)

        case "zero_to_pos"
            label = "0 -> +I";

        case "pos_to_neg"
            label = "+I -> -I";

        case "neg_to_pos"
            label = "-I -> +I";

        case "neg_to_zero"
            label = "-I -> 0";

        otherwise
            label = "unexpected";
    end
end

