%% Stage2_ClassifyCurrentResponses.m
% OPENXSTIM SCALABLE STAGE 2
% COMMAND-GUIDED, NON-CASCADING CURRENT-RESPONSE CLASSIFIER
%
% Purpose
% -------
% Stage 1 already provides one validated complete 41-command packet for
% every capture.
%
% Stage 2 pairs each Stage 1 command with its physical CH3 response while
% preserving absolute current information for later system identification.
%
% This version replaces the old "state-pair first" classifier with the
% experimentally validated approach developed in Stage2A:
%
%   Stage 1 command
%       ->
%   transition-class delay prior
%       ->
%   non-overlapping local response cell
%       ->
%   strongest gradient of the expected direction
%       ->
%   normalized-gradient acceptance test
%
% This prevents the previous failure mode where one rejected edge caused
% all later events to shift by approximately one bipolar cycle.
%
% IMPORTANT CURRENT CONVENTION
% ----------------------------
% The commanded current is PEAK TO PEAK.
%
% Therefore measured current is compared to command using:
%
%   Ipp_measured = I_positive - I_negative
%                = |I_positive| + |I_negative|
%
% Positive and negative one-sided levels are still preserved separately for
% symmetry and droop analysis.
%
% GRADIENT THRESHOLD
% ------------------
% Stage2A robustness analysis established a conservative normalized
% bipolar-switch threshold:
%
%   |dI/dt| / Ipp_measured > Tnorm
%
% where the robustness MAT file provides Tnorm. The current experimentally
% derived conservative midpoint is approximately:
%
%   0.11553 1/us
%
% This threshold was robust across:
%
%   5, 10, 15, 20, 30, 50 mA p-p
%
% and passive-edge guards:
%
%   8, 10, 15, 20 us
%
% Boundary transitions:
%
%   0 -> +I
%   -I -> 0
%
% are only half-step transitions. They are found using the same
% non-overlapping command-guided timing cells and expected gradient
% direction. Their step-normalized gradient is saved as QC, but the bipolar
% p-p threshold is NOT used as a hard rejection rule for them.
%
% STATE-PAIR CHECK
% ----------------
% The old pre/post POSITIVE / NEGATIVE / ZERO state test is still calculated
% for diagnostics, but it is now QC only. It can no longer delete a real
% high-current switching edge.
%
% OUTPUTS
% -------
% Per capture:
%   01_PhysicalResponseEvents.csv
%   02_PhysicalPhases.csv
%   03_PulsePeakToPeakCurrent.csv
%   Stage2_CurrentResponseResults.mat
%   Stage2_Diagnostic.png
%   Stage2_PhaseClassificationDiagnostic.png
%
% Master:
%   Stage2CaptureSummary.csv
%   Stage2PhysicalEvents.csv
%   Stage2PhysicalPhases.csv
%   Stage2PulsePeakToPeakCurrent.csv
%   Stage2CurrentLevelSummary.csv
%   Stage2MasterResults.mat
%   Stage2_MultiCurrentSummary.png
%   Stage2_PhaseClassificationOverview.png
%   Stage2_PhaseClassificationZoom.png
%
% The configured Stage 2 output folder is replaced on each run so stale
% V1/V2 files are not mixed with the final classifier outputs.
%
% Stage 2 deliberately does NOT perform fast-transition normalization or
% transfer-function fitting. Those belong to Stage 3 and later.

clear;
clc;
close all;

%% ========================================================================
% USER SETTINGS
% ========================================================================

cfg = struct();

cfg.DATA_ROOT = ...
    fileparts(mfilename("fullpath")); % Put the CSV files in the same folder as this script.

cfg.ANALYSIS_FOLDER = ...
    fullfile(cfg.DATA_ROOT,"Matlab Analysis");

cfg.STAGE1_MASTER_FILE = ...
    fullfile( ...
    cfg.ANALYSIS_FOLDER, ...
    "Stage1_PacketClassification", ...
    "Stage1MasterResults.mat");

cfg.ROBUSTNESS_FILE = ...
    fullfile( ...
    cfg.ANALYSIS_FOLDER, ...
    "Stage2A_GradientThresholdRobustness", ...
    "Stage2A_GradientThresholdRobustness.mat");

cfg.OUTPUT_FOLDER = ...
    fullfile( ...
    cfg.ANALYSIS_FOLDER, ...
    "Stage2_CurrentResponseClassification");

% Replace the previous Stage 2 output folder completely on every run.
% This prevents stale V1 files from being mixed with the final classifier.
cfg.OVERWRITE_EXISTING_STAGE2_FOLDER = true;

% Per-capture figures remain hidden by default to avoid 30 windows.
% Master diagnostics are shown at the end for inspection.
cfg.SHOW_MASTER_FIGURES = true;

% Number of pulses shown in the labelled phase-classification zoom.
cfg.CLASSIFICATION_ZOOM_PULSES = 3;

% -------------------------------------------------------------------------
% RAW CHANNEL / LOAD
% -------------------------------------------------------------------------

cfg.OUTPUT_CHANNEL = 3;
cfg.R_LOAD_OHM = 1000;

% -------------------------------------------------------------------------
% SIGNAL PROCESSING
% -------------------------------------------------------------------------

% Same smoothing used during the threshold robustness study.
cfg.OUTPUT_SMOOTH_US = 0.50;

% -------------------------------------------------------------------------
% FALLBACK CLASSIFIER CONSTANTS
%
% These are used only if the Stage2A robustness MAT file is unavailable.
% Prefer loading the experimentally derived values from that file.
% -------------------------------------------------------------------------

cfg.FALLBACK_BIPOLAR_THRESHOLD_NORM_PER_US = 0.11553066;

cfg.FALLBACK_DELAY_PRIOR = table( ...
    ["zero_to_pos";"pos_to_neg";"neg_to_pos";"neg_to_zero"], ...
    [748.08;967.84;988.96;987.84], ...
    'VariableNames',{'TransitionClass','MedianDelay_us'});

% -------------------------------------------------------------------------
% COMMAND-GUIDED RESPONSE CELLS
% -------------------------------------------------------------------------

% Large enough to tolerate modest current dependence, but each cell is
% clipped halfway between neighbouring expected response centres.
cfg.GUIDED_SEARCH_HALF_WIDTH_US = 550;

% -------------------------------------------------------------------------
% ZERO / CURRENT SCALE
% -------------------------------------------------------------------------

cfg.ZERO_BASELINE_WINDOW_MS = 1.0;
cfg.ZERO_BASELINE_GUARD_US = 50;

cfg.RESPONSE_SEARCH_BEFORE_FIRST_COMMAND_MS = 0.10;
cfg.RESPONSE_SEARCH_AFTER_LAST_COMMAND_MS = 2.25;

% Initial p-p scale estimate used by the classifier before phase extraction.
cfg.POSITIVE_LEVEL_PERCENTILE = 95;
cfg.NEGATIVE_LEVEL_PERCENTILE = 5;

% -------------------------------------------------------------------------
% STATE-PAIR QC ONLY
% -------------------------------------------------------------------------

cfg.STATE_LEVEL_GUARD_US = 30;
cfg.STATE_LEVEL_WINDOW_US = 100;

cfg.BROAD_ZERO_NOISE_SIGMAS = 8;
cfg.BROAD_ZERO_FRACTION_OF_HALF_EXCURSION = 0.12;

% -------------------------------------------------------------------------
% PASSIVE PHASE EXTRACTION
% -------------------------------------------------------------------------

% Robustness analysis showed that 15 us is comfortably beyond the ~5 us
% fast electrical transition while preserving passive dynamics.
cfg.PHASE_EDGE_GUARD_US = 15;

% Early and late physical-current levels are medians over these windows.
cfg.PHASE_LEVEL_WINDOW_US = 100;

% -------------------------------------------------------------------------
% BOUNDARY EVENT QC
% -------------------------------------------------------------------------

% Boundary events are accepted from timing + direction.
% Their normalized-by-half-step gradient is compared to the same numerical
% threshold only as a QC indicator, NOT as a hard acceptance criterion.
cfg.FLAG_WEAK_BOUNDARY_GRADIENT = true;

% -------------------------------------------------------------------------
% PASS / WARNING RULES
% -------------------------------------------------------------------------

cfg.EXPECTED_COMMAND_EVENTS = 41;
cfg.EXPECTED_BIPOLAR_EVENTS = 39;
cfg.EXPECTED_PHYSICAL_PHASES = 40;
cfg.EXPECTED_PULSES = 20;

% A capture is PASS only when all 39 bipolar transitions pass the robust
% gradient threshold and both boundary transitions are located.
cfg.REQUIRE_ALL_BIPOLAR_TRANSITIONS = true;

% State-pair QC failures do NOT make a capture fail.
cfg.STATE_QC_AFFECTS_STATUS = false;

% -------------------------------------------------------------------------
% PLOTTING
% -------------------------------------------------------------------------

cfg.SAVE_PLOTS = true;
cfg.SHOW_FIGURES = false;
cfg.FIGURE_RESOLUTION_DPI = 180;
cfg.MAX_PLOT_POINTS = 100000;

%% ========================================================================
% INPUT CHECKS / OUTPUT FOLDER
% ========================================================================

if ~isfile(cfg.STAGE1_MASTER_FILE)
    error("Stage 1 master file not found:\n%s",cfg.STAGE1_MASTER_FILE);
end

[~,outputFolderName] = fileparts(cfg.OUTPUT_FOLDER);

if string(outputFolderName) ~= "Stage2_CurrentResponseClassification"
    error("Safety check failed: unexpected Stage 2 output folder name: %s", ...
        outputFolderName);
end

if cfg.OVERWRITE_EXISTING_STAGE2_FOLDER && isfolder(cfg.OUTPUT_FOLDER)

    fprintf("\nReplacing existing Stage 2 output folder:\n%s\n", ...
        cfg.OUTPUT_FOLDER);

    rmdir(cfg.OUTPUT_FOLDER,'s');
end

if ~isfolder(cfg.OUTPUT_FOLDER)
    mkdir(cfg.OUTPUT_FOLDER);
end

%% ========================================================================
% LOAD CLASSIFIER CALIBRATION FROM STAGE 2A ROBUSTNESS ANALYSIS
% ========================================================================

classifierSource = "fallback_constants";

bipolarThresholdNorm_per_us = ...
    cfg.FALLBACK_BIPOLAR_THRESHOLD_NORM_PER_US;

DelayPriors = cfg.FALLBACK_DELAY_PRIOR;

worstPassiveUpperNorm_per_us = NaN;
worstSwitchLowerNorm_per_us = NaN;

if isfile(cfg.ROBUSTNESS_FILE)

    R = load(cfg.ROBUSTNESS_FILE);

    if isfield(R,"ConservativeThresholdSummary")

        C = R.ConservativeThresholdSummary;

        if ismember( ...
                "ConservativeMidpointThreshold_per_us", ...
                string(C.Properties.VariableNames))

            x = C.ConservativeMidpointThreshold_per_us(1);

            if isfinite(x) && x>0

                bipolarThresholdNorm_per_us = x;
                classifierSource = "Stage2A_robustness";
            end
        end

        if ismember( ...
                "WorstCasePassiveUpperNorm_per_us", ...
                string(C.Properties.VariableNames))

            worstPassiveUpperNorm_per_us = ...
                C.WorstCasePassiveUpperNorm_per_us(1);
        end

        if ismember( ...
                "WorstCaseSwitchLowerNorm_per_us", ...
                string(C.Properties.VariableNames))

            worstSwitchLowerNorm_per_us = ...
                C.WorstCaseSwitchLowerNorm_per_us(1);
        end
    end

    if isfield(R,"DelayPriors")

        D = R.DelayPriors;

        required = ["TransitionClass","MedianDelay_us"];

        if all(ismember(required,string(D.Properties.VariableNames)))

            DelayPriors = ...
                D(:,required);
        end
    end
end

fprintf("\n============================================================\n");
fprintf("OPENXSTIM STAGE 2: CURRENT RESPONSE CLASSIFICATION\n");
fprintf("============================================================\n");

fprintf("Classifier source              : %s\n",classifierSource);
fprintf("Bipolar normalized threshold   : %.8f 1/us\n", ...
    bipolarThresholdNorm_per_us);

if isfinite(worstPassiveUpperNorm_per_us)
    fprintf("Worst passive upper bound      : %.8f 1/us\n", ...
        worstPassiveUpperNorm_per_us);
end

if isfinite(worstSwitchLowerNorm_per_us)
    fprintf("Worst switch lower bound       : %.8f 1/us\n", ...
        worstSwitchLowerNorm_per_us);
end

fprintf("Passive phase edge guard       : %.3f us\n", ...
    cfg.PHASE_EDGE_GUARD_US);

fprintf("\nDelay priors used:\n");
disp(DelayPriors);

%% ========================================================================
% LOAD STAGE 1
% ========================================================================

S1 = load(cfg.STAGE1_MASTER_FILE);

if ~isfield(S1,"CaptureSummary") || ~isfield(S1,"resultFiles")
    error("Stage 1 master file must contain CaptureSummary and resultFiles.");
end

stage1Summary = S1.CaptureSummary;
stage1ResultFiles = string(S1.resultFiles);

nCaptures = height(stage1Summary);

fprintf("Captures found in Stage 1      : %d\n",nCaptures);

%% ========================================================================
% MASTER CONTAINERS
% ========================================================================

captureSummaryParts = cell(nCaptures,1);
eventParts = cell(nCaptures,1);
phaseParts = cell(nCaptures,1);
pulseParts = cell(nCaptures,1);
resultFiles = strings(nCaptures,1);

%% ========================================================================
% PROCESS CAPTURES ONE AT A TIME
% ========================================================================

for c = 1:nCaptures

    captureID = stage1Summary.CaptureID(c);
    attemptNumber = stage1Summary.AttemptNumber(c);
    commandCurrent_mA = stage1Summary.CommandCurrent_mA(c);
    captureWithinAttempt = stage1Summary.CaptureWithinAttempt(c);
    fileName = string(stage1Summary.FileName(c));

    fprintf("\n------------------------------------------------------------\n");
    fprintf("CAPTURE %d / %d | %.3g mA p-p\n", ...
        c,nCaptures,commandCurrent_mA);
    fprintf("------------------------------------------------------------\n");

    try

        %% ----------------------------------------------------------------
        % LOAD STAGE 1 PER-CAPTURE RESULT
        % -----------------------------------------------------------------

        if c>numel(stage1ResultFiles) || ...
                strlength(stage1ResultFiles(c))==0 || ...
                ~isfile(stage1ResultFiles(c))

            error("Stage 1 per-capture MAT file is missing.");
        end

        S = load(stage1ResultFiles(c));

        if ~isfield(S,"result")
            error("Stage 1 per-capture MAT contains no result.");
        end

        R1 = S.result;

        if ~isfield(R1,"selectedCommandTable") || ...
                isempty(R1.selectedCommandTable)

            error("No selected complete Stage 1 command packet.");
        end

        commands = R1.selectedCommandTable;
        csvPath = string(R1.csvPath);

        if ~isfile(csvPath)
            error("Raw CSV not found: %s",csvPath);
        end

        if height(commands)~=cfg.EXPECTED_COMMAND_EVENTS
            error( ...
                "Selected packet contains %d commands, expected %d.", ...
                height(commands),cfg.EXPECTED_COMMAND_EVENTS);
        end

        %% ----------------------------------------------------------------
        % LOAD FULL-RESOLUTION CSV
        % -----------------------------------------------------------------

        [data,t,t0,Ts,header] = loadRigolMemoryCSV(csvPath);

        Fs = 1/Ts;

        if size(data,2)<cfg.OUTPUT_CHANNEL
            error("CSV does not contain CH3.");
        end

        outputV = data(:,cfg.OUTPUT_CHANNEL);

        currentRaw_mA = ...
            1000*outputV/cfg.R_LOAD_OHM;

        smoothSamples = ...
            max(3,round(cfg.OUTPUT_SMOOTH_US*1e-6/Ts));

        if mod(smoothSamples,2)==0
            smoothSamples = smoothSamples+1;
        end

        currentSmooth_mA = ...
            movmean(currentRaw_mA,smoothSamples);

        gradient_mA_per_us = ...
            gradient(currentSmooth_mA,Ts)/1e6;

        absGradient_mA_per_us = ...
            abs(gradient_mA_per_us);

        commandEvent = ...
            commands.EventNumberWithinPacket(:);

        commandTime_s = ...
            commands.CommandTime_s(:);

        commandClass = ...
            string(commands.TransitionClass(:));

        pulseNumber = ...
            commands.PulseNumber(:);

        nCommands = ...
            height(commands);

        fprintf("File                         : %s\n",csvPath);
        fprintf("Samples                      : %d\n",numel(t));
        fprintf("Fs                           : %.6f MSa/s\n",Fs/1e6);

        %% =================================================================
        % PART A: LOCAL ZERO + INITIAL PEAK-TO-PEAK SCALE ESTIMATE
        % =================================================================

        zeroEnd_s = ...
            commandTime_s(1) ...
            - cfg.ZERO_BASELINE_GUARD_US*1e-6;

        zeroStart_s = ...
            max( ...
            t(1), ...
            zeroEnd_s-cfg.ZERO_BASELINE_WINDOW_MS*1e-3);

        zeroMask = ...
            t>=zeroStart_s & ...
            t<=zeroEnd_s;

        if nnz(zeroMask)<20
            error("Insufficient local zero baseline.");
        end

        zeroLevel_mA = ...
            median(currentRaw_mA(zeroMask),'omitnan');

        zeroNoiseSD_mA = ...
            robustSigma(currentRaw_mA(zeroMask));

        gradientNoiseSD_mA_per_us = ...
            robustSigma(gradient_mA_per_us(zeroMask));

        responseSearchStart_s = ...
            max( ...
            t(1), ...
            commandTime_s(1) ...
            - cfg.RESPONSE_SEARCH_BEFORE_FIRST_COMMAND_MS*1e-3);

        responseSearchEnd_s = ...
            min( ...
            t(end), ...
            commandTime_s(end) ...
            + cfg.RESPONSE_SEARCH_AFTER_LAST_COMMAND_MS*1e-3);

        responseSearchMask = ...
            t>=responseSearchStart_s & ...
            t<=responseSearchEnd_s;

        localCurrent = ...
            currentRaw_mA(responseSearchMask);

        positiveLevelEstimate_mA = ...
            percentileLocal( ...
            localCurrent, ...
            cfg.POSITIVE_LEVEL_PERCENTILE);

        negativeLevelEstimate_mA = ...
            percentileLocal( ...
            localCurrent, ...
            cfg.NEGATIVE_LEVEL_PERCENTILE);

        positiveHalfEstimate_mA = ...
            positiveLevelEstimate_mA-zeroLevel_mA;

        negativeHalfEstimate_mA = ...
            zeroLevel_mA-negativeLevelEstimate_mA;

        measuredIppScale_mA = ...
            positiveLevelEstimate_mA-negativeLevelEstimate_mA;

        if ~isfinite(measuredIppScale_mA) || measuredIppScale_mA<=0
            error("Could not estimate positive peak-to-peak current scale.");
        end

        fprintf("\nCURRENT SCALE\n");
        fprintf("Zero level                    : %.6f mA\n",zeroLevel_mA);
        fprintf("Positive robust level         : %.6f mA\n", ...
            positiveLevelEstimate_mA);
        fprintf("Negative robust level         : %.6f mA\n", ...
            negativeLevelEstimate_mA);
        fprintf("Initial measured Ipp scale    : %.6f mA\n", ...
            measuredIppScale_mA);
        fprintf("Initial measured/command      : %.6f\n", ...
            measuredIppScale_mA/commandCurrent_mA);

        %% =================================================================
        % PART B: EXPECTED RESPONSE CENTRES
        % =================================================================

        priorDelay_us = NaN(nCommands,1);
        expectedResponseCentre_s = NaN(nCommands,1);
        expectedGradientDirection = NaN(nCommands,1);

        for e = 1:nCommands

            p = find( ...
                string(DelayPriors.TransitionClass)==commandClass(e), ...
                1);

            if isempty(p)
                error("No delay prior for command class %s.",commandClass(e));
            end

            priorDelay_us(e) = ...
                DelayPriors.MedianDelay_us(p);

            expectedResponseCentre_s(e) = ...
                commandTime_s(e) ...
                + priorDelay_us(e)*1e-6;

            expectedGradientDirection(e) = ...
                transitionDirection(commandClass(e));
        end

        %% =================================================================
        % PART C: NON-OVERLAPPING COMMAND-GUIDED EDGE SEARCH
        % =================================================================

        searchStart_s = NaN(nCommands,1);
        searchEnd_s = NaN(nCommands,1);

        guidedResponseTime_s = NaN(nCommands,1);
        guidedDelay_us = NaN(nCommands,1);

        signedPeakGradient_mA_per_us = NaN(nCommands,1);
        absPeakGradient_mA_per_us = NaN(nCommands,1);

        expectedPhysicalStep_mA = NaN(nCommands,1);

        normGradientByIpp_per_us = NaN(nCommands,1);
        normGradientByExpectedStep_per_us = NaN(nCommands,1);

        candidateFound = false(nCommands,1);
        bipolarThresholdPass = false(nCommands,1);
        boundaryGradientQC = false(nCommands,1);

        isBipolar = ...
            commandClass=="pos_to_neg" | ...
            commandClass=="neg_to_pos";

        isBoundary = ...
            commandClass=="zero_to_pos" | ...
            commandClass=="neg_to_zero";

        for e = 1:nCommands

            lo = ...
                expectedResponseCentre_s(e) ...
                - cfg.GUIDED_SEARCH_HALF_WIDTH_US*1e-6;

            hi = ...
                expectedResponseCentre_s(e) ...
                + cfg.GUIDED_SEARCH_HALF_WIDTH_US*1e-6;

            if e>1

                lo = max( ...
                    lo, ...
                    0.5*( ...
                    expectedResponseCentre_s(e-1) ...
                    + expectedResponseCentre_s(e)));
            end

            if e<nCommands

                hi = min( ...
                    hi, ...
                    0.5*( ...
                    expectedResponseCentre_s(e) ...
                    + expectedResponseCentre_s(e+1)));
            end

            lo = max(lo,responseSearchStart_s);
            hi = min(hi,responseSearchEnd_s);

            searchStart_s(e) = lo;
            searchEnd_s(e) = hi;

            directionMask = ...
                sign(gradient_mA_per_us) ...
                == expectedGradientDirection(e);

            searchMask = ...
                t>=lo & ...
                t<=hi & ...
                directionMask;

            idx = ...
                find(searchMask);

            if isempty(idx)
                continue;
            end

            [~,ii] = ...
                max(absGradient_mA_per_us(idx));

            edgeIdx = ...
                idx(ii);

            candidateFound(e) = true;

            guidedResponseTime_s(e) = ...
                t(edgeIdx);

            guidedDelay_us(e) = ...
                (guidedResponseTime_s(e)-commandTime_s(e))*1e6;

            signedPeakGradient_mA_per_us(e) = ...
                gradient_mA_per_us(edgeIdx);

            absPeakGradient_mA_per_us(e) = ...
                absGradient_mA_per_us(edgeIdx);

            expectedPhysicalStep_mA(e) = ...
                expectedPhysicalStep( ...
                commandClass(e), ...
                positiveHalfEstimate_mA, ...
                negativeHalfEstimate_mA, ...
                measuredIppScale_mA);

            normGradientByIpp_per_us(e) = ...
                absPeakGradient_mA_per_us(e) ...
                / measuredIppScale_mA;

            normGradientByExpectedStep_per_us(e) = ...
                absPeakGradient_mA_per_us(e) ...
                / expectedPhysicalStep_mA(e);

            if isBipolar(e)

                bipolarThresholdPass(e) = ...
                    normGradientByIpp_per_us(e) ...
                    > bipolarThresholdNorm_per_us;

            elseif isBoundary(e)

                boundaryGradientQC(e) = ...
                    normGradientByExpectedStep_per_us(e) ...
                    > bipolarThresholdNorm_per_us;
            end
        end

        %% =================================================================
        % PART D: ACCEPTANCE + STATE-PAIR QC
        % =================================================================

        acceptedResponse = false(nCommands,1);
        physicalEdgeObserved = false(nCommands,1);
        responseTimeSource = strings(nCommands,1);

        matchStatus = strings(nCommands,1);

        preLevel_mA = NaN(nCommands,1);
        postLevel_mA = NaN(nCommands,1);
        localDelta_mA = NaN(nCommands,1);

        observedPreState = strings(nCommands,1);
        observedPostState = strings(nCommands,1);
        observedTransitionClass = strings(nCommands,1);
        statePairQC = false(nCommands,1);

        broadZeroTolerance_mA = ...
            max( ...
            cfg.BROAD_ZERO_NOISE_SIGMAS*zeroNoiseSD_mA, ...
            cfg.BROAD_ZERO_FRACTION_OF_HALF_EXCURSION ...
            * min(positiveHalfEstimate_mA,negativeHalfEstimate_mA));

        stateGuardSamples = ...
            max(1,round(cfg.STATE_LEVEL_GUARD_US*1e-6/Ts));

        stateWindowSamples = ...
            max(2,round(cfg.STATE_LEVEL_WINDOW_US*1e-6/Ts));

        for e = 1:nCommands

            if ~candidateFound(e)

                matchStatus(e) = ...
                    "unmatched_no_directional_candidate";

                continue;
            end

            if isBipolar(e)

                if bipolarThresholdPass(e)

                    acceptedResponse(e) = true;
                    physicalEdgeObserved(e) = true;
                    responseTimeSource(e) = "observed_gradient";
                    matchStatus(e) = ...
                        "matched_bipolar_gradient";

                else

                    matchStatus(e) = ...
                        "rejected_bipolar_below_threshold";
                end

            elseif isBoundary(e)

                % Boundary events close the physical packet. If a strong
                % half-step edge exists, use it directly. If the output has
                % already collapsed near zero, there may be no observable
                % final -I -> 0 edge. In that case use the class-specific
                % expected response time as a segmentation surrogate rather
                % than pretending that a small noise gradient is the edge.
                acceptedResponse(e) = true;

                if boundaryGradientQC(e)

                    physicalEdgeObserved(e) = true;
                    responseTimeSource(e) = "observed_gradient";
                    matchStatus(e) = ...
                        "matched_boundary_gradient";

                else

                    physicalEdgeObserved(e) = false;
                    responseTimeSource(e) = "timing_surrogate";
                    matchStatus(e) = ...
                        "matched_boundary_timing_surrogate";
                end
            end

            % -------------------------------------------------------------
            % Old state-pair logic is now DIAGNOSTIC ONLY.
            % -------------------------------------------------------------

            [~,edgeIdx] = ...
                min(abs(t-guidedResponseTime_s(e)));

            preEnd = ...
                edgeIdx-stateGuardSamples;

            preStart = ...
                preEnd-stateWindowSamples+1;

            postStart = ...
                edgeIdx+stateGuardSamples;

            postEnd = ...
                postStart+stateWindowSamples-1;

            if preStart>=1 && postEnd<=numel(t)

                preLevel_mA(e) = ...
                    median( ...
                    currentRaw_mA(preStart:preEnd), ...
                    'omitnan');

                postLevel_mA(e) = ...
                    median( ...
                    currentRaw_mA(postStart:postEnd), ...
                    'omitnan');

                localDelta_mA(e) = ...
                    postLevel_mA(e)-preLevel_mA(e);

                observedPreState(e) = ...
                    broadStateLabel( ...
                    preLevel_mA(e), ...
                    zeroLevel_mA, ...
                    broadZeroTolerance_mA);

                observedPostState(e) = ...
                    broadStateLabel( ...
                    postLevel_mA(e), ...
                    zeroLevel_mA, ...
                    broadZeroTolerance_mA);

                observedTransitionClass(e) = ...
                    physicalTransitionFromLabels( ...
                    observedPreState(e), ...
                    observedPostState(e));

                statePairQC(e) = ...
                    observedTransitionClass(e)==commandClass(e);
            end
        end

        responseTime_s = NaN(nCommands,1);
        responseDelay_us = NaN(nCommands,1);

        observedAccepted = ...
            acceptedResponse & physicalEdgeObserved;

        responseTime_s(observedAccepted) = ...
            guidedResponseTime_s(observedAccepted);

        responseDelay_us(observedAccepted) = ...
            guidedDelay_us(observedAccepted);

        surrogateBoundary = ...
            acceptedResponse & isBoundary & ~physicalEdgeObserved;

