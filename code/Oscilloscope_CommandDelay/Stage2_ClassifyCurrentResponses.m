            expectedResponseCentre_s(surrogateBoundary);

        responseDelay_us(surrogateBoundary) = ...
            priorDelay_us(surrogateBoundary);

        PhysicalEvents = table( ...
            repmat(captureID,nCommands,1), ...
            repmat(attemptNumber,nCommands,1), ...
            repmat(commandCurrent_mA,nCommands,1), ...
            repmat(captureWithinAttempt,nCommands,1), ...
            pulseNumber, ...
            commandEvent, ...
            commandClass, ...
            isBipolar, ...
            isBoundary, ...
            commandTime_s, ...
            priorDelay_us, ...
            expectedResponseCentre_s, ...
            searchStart_s, ...
            searchEnd_s, ...
            candidateFound, ...
            guidedResponseTime_s, ...
            guidedDelay_us, ...
            expectedGradientDirection, ...
            signedPeakGradient_mA_per_us, ...
            absPeakGradient_mA_per_us, ...
            repmat(measuredIppScale_mA,nCommands,1), ...
            expectedPhysicalStep_mA, ...
            normGradientByIpp_per_us, ...
            normGradientByExpectedStep_per_us, ...
            bipolarThresholdPass, ...
            boundaryGradientQC, ...
            acceptedResponse, ...
            physicalEdgeObserved, ...
            responseTimeSource, ...
            responseTime_s, ...
            responseDelay_us, ...
            preLevel_mA, ...
            postLevel_mA, ...
            localDelta_mA, ...
            observedPreState, ...
            observedPostState, ...
            observedTransitionClass, ...
            statePairQC, ...
            matchStatus, ...
            'VariableNames',{ ...
            'CaptureID', ...
            'AttemptNumber', ...
            'CommandCurrent_mA', ...
            'CaptureWithinAttempt', ...
            'PulseNumber', ...
            'CommandEvent', ...
            'CommandClass', ...
            'IsBipolar', ...
            'IsBoundary', ...
            'CommandTime_s', ...
            'ReferenceDelay_us', ...
            'ExpectedResponseCentre_s', ...
            'SearchStart_s', ...
            'SearchEnd_s', ...
            'CandidateFound', ...
            'GuidedResponseTime_s', ...
            'GuidedDelay_us', ...
            'ExpectedGradientDirection', ...
            'SignedPeakGradient_mA_per_us', ...
            'AbsPeakGradient_mA_per_us', ...
            'MeasuredIppScale_mA', ...
            'ExpectedPhysicalStep_mA', ...
            'NormGradientByIpp_per_us', ...
            'NormGradientByExpectedStep_per_us', ...
            'BipolarThresholdPass', ...
            'BoundaryGradientQC', ...
            'AcceptedResponse', ...
            'PhysicalEdgeObserved', ...
            'ResponseTimeSource', ...
            'ResponseTime_s', ...
            'Delay_us', ...
            'PreLevel_mA', ...
            'PostLevel_mA', ...
            'LocalDelta_mA', ...
            'ObservedPreState', ...
            'ObservedPostState', ...
            'ObservedTransitionClass', ...
            'StatePairQC', ...
            'MatchStatus'});

        nAccepted = nnz(acceptedResponse);
        nBipolarPass = nnz(isBipolar & bipolarThresholdPass);
        nBipolarTotal = nnz(isBipolar);
