                captureID, ...
                attemptNumber, ...
                commandCurrent_mA, ...
                captureWithinAttempt, ...
                phaseCounter, ...
                phasePulseNumber, ...
                polarity, ...
                phaseClass, ...
                sourceClass, ...
                nextClass, ...
                fastStart_s, ...
                fastEnd_s, ...
                passiveStart_s, ...
                passiveEnd_s, ...
