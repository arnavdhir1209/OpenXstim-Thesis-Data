%% Stage2A_GradientThresholdAnalysis_v2.m
% OPENXSTIM GRADIENT-SEPARATION ANALYSIS, V2
%
% Purpose
% -------
% Diagnose whether a gradient threshold can reliably separate:
%
%   1. true commanded switching edges
%   2. fast passive droop
%   3. slow passive droop
%
% This version fixes two problems in the first Stage2A:
%
%   - The previous script required passive peaks to exceed a 6-sigma
%     noise floor. In these captures that retained ZERO passive peaks.
%
%   - It excluded +/-60 us around every switching edge. That is too wide
%     when the fast passive droop may occur soon after the true transition.
%
% V2 therefore:
%
%   - uses Stage 1 commands and clean 5/10 mA Stage 2 results to build
%     class-specific delay priors
%   - finds one command-guided switching edge for EVERY command inside a
%     non-overlapping temporal cell
%   - defines each physical phase between successive guided switch edges
%   - excludes only a short guard around the fast transition
%   - measures the MAXIMUM passive |dI/dt| inside every phase
%   - also records 99th percentile and median passive |dI/dt| per phase
%   - compares the upper distribution of per-phase passive maxima against
%     the lower distribution of true bipolar-switch gradients
%   - performs the comparison in both raw mA/us and normalized 1/us units
%
% Current convention
% ------------------
% Command current is PEAK TO PEAK.
%
% Measured current is therefore:
%
%   Ipp = Ipositive - Inegative
%       = |Ipositive| + |Inegative|
%
% No Stage 1 or Stage 2 output is overwritten.

clear;
clc;
close all;

%% ========================================================================
% USER SETTINGS
% ========================================================================

cfg = struct();

cfg.DATA_ROOT = ...
    fileparts(mfilename("fullpath")); % Put the CSV files in the same folder as this script.

cfg.ANALYSIS_FOLDER = ...
    fullfile(cfg.DATA_ROOT,"Matlab Analysis");

cfg.STAGE1_MASTER_FILE = ...
    fullfile( ...
    cfg.ANALYSIS_FOLDER, ...
    "Stage1_PacketClassification", ...
    "Stage1MasterResults.mat");

cfg.STAGE2_MASTER_FILE = ...
    fullfile( ...
    cfg.ANALYSIS_FOLDER, ...
    "Stage2_CurrentResponseClassification", ...
    "Stage2MasterResults.mat");

cfg.OUTPUT_FOLDER = ...
    fullfile( ...
    cfg.ANALYSIS_FOLDER, ...
    "Stage2A_GradientThresholdAnalysis");

cfg.OUTPUT_CHANNEL = 3;
cfg.R_LOAD_OHM = 1000;

% Keep the same smoothing as the current Stage 2 classifier.
cfg.OUTPUT_SMOOTH_US = 0.50;

% Use only the clean low-current PASS captures for delay priors.
cfg.REFERENCE_MAX_COMMAND_CURRENT_mA = 10;

% Broad guided search around the expected response centre.
% Search cells are clipped halfway between neighbouring expected responses,
% so one event cannot steal the next pulse's transition.
cfg.GUIDED_SEARCH_HALF_WIDTH_US = 550;

% Local zero estimate.
cfg.ZERO_BASELINE_WINDOW_MS = 1.0;
cfg.ZERO_BASELINE_GUARD_US = 50;

% Whole selected-burst response window.
cfg.RESPONSE_SEARCH_BEFORE_FIRST_COMMAND_MS = 0.10;
cfg.RESPONSE_SEARCH_AFTER_LAST_COMMAND_MS = 2.25;

% Robust current-scale estimate.
cfg.POSITIVE_LEVEL_PERCENTILE = 95;
cfg.NEGATIVE_LEVEL_PERCENTILE = 5;

% -------------------------------------------------------------------------
% PASSIVE PHASE ANALYSIS
% -------------------------------------------------------------------------

% Fast switching itself is about 5 us. A 15 us guard keeps the fast edge
% out while still retaining rapid passive behaviour immediately afterwards.
cfg.PASSIVE_EDGE_GUARD_US = 15;

% Common passive sampling interval for distribution plots.
cfg.PASSIVE_SAMPLE_DT_US = 1.0;

% Report an "early passive" maximum as well. This is useful for checking
% whether the fast droop is concentrated soon after each switch.
cfg.EARLY_PASSIVE_WINDOW_US = 250;

% -------------------------------------------------------------------------
% ROBUST SEPARATION METRICS
% -------------------------------------------------------------------------

% Main passive statistic:
% one maximum |dI/dt| per physical phase.
%
% This gives ~40 passive maxima per capture rather than millions of
% correlated samples.
cfg.PASSIVE_PHASE_MAX_UPPER_PERCENTILE = 99;

% Main switching statistic:
% lower tail of the actual BIPOLAR switching-gradient distribution.
cfg.BIPOLAR_SWITCH_LOWER_PERCENTILE = 1;

% Suggested threshold is only reported when a positive gap exists.
cfg.THRESHOLD_MIDPOINT_MODE = "arithmetic";

% -------------------------------------------------------------------------
% FIGURES
% -------------------------------------------------------------------------

cfg.SAVE_PLOTS = true;
cfg.SHOW_FIGURES = false;
cfg.FIGURE_RESOLUTION_DPI = 180;
cfg.MAX_PLOT_POINTS = 100000;

%% ========================================================================
% INPUT CHECKS
% ========================================================================

if ~isfile(cfg.STAGE1_MASTER_FILE)
    error("Stage 1 master file not found:\n%s",cfg.STAGE1_MASTER_FILE);
end

if ~isfile(cfg.STAGE2_MASTER_FILE)
    error("Stage 2 master file not found:\n%s",cfg.STAGE2_MASTER_FILE);
end

if ~isfolder(cfg.OUTPUT_FOLDER)
    mkdir(cfg.OUTPUT_FOLDER);
end

%% ========================================================================
% LOAD STAGE 1 / STAGE 2
% ========================================================================

S1 = load(cfg.STAGE1_MASTER_FILE);
S2 = load(cfg.STAGE2_MASTER_FILE);

if ~isfield(S1,"CaptureSummary") || ~isfield(S1,"resultFiles")
    error("Stage 1 master file must contain CaptureSummary and resultFiles.");
end

if ~isfield(S2,"CaptureSummary") || ~isfield(S2,"PhysicalEvents")
    error("Stage 2 master file must contain CaptureSummary and PhysicalEvents.");
end

stage1Summary = S1.CaptureSummary;
stage1ResultFiles = string(S1.resultFiles);

stage2Summary = S2.CaptureSummary;
stage2PhysicalEvents = S2.PhysicalEvents;

%% ========================================================================
% CLASS-SPECIFIC DELAY PRIORS FROM CLEAN 5/10 mA CAPTURES
% ========================================================================

referenceCaptureIDs = ...
    stage2Summary.CaptureID( ...
    stage2Summary.Stage2Status=="PASS" & ...
    stage2Summary.CommandCurrent_mA<=cfg.REFERENCE_MAX_COMMAND_CURRENT_mA);

referenceEvents = ...
    stage2PhysicalEvents( ...
    ismember(stage2PhysicalEvents.CaptureID,referenceCaptureIDs) & ...
    startsWith(string(stage2PhysicalEvents.MatchStatus),"matched"),:);

classes = [ ...
    "zero_to_pos", ...
    "pos_to_neg", ...
    "neg_to_pos", ...
    "neg_to_zero"];

TransitionClass = classes(:);
NReferenceEvents = zeros(numel(classes),1);
MedianDelay_us = NaN(numel(classes),1);
RobustSD_us = NaN(numel(classes),1);
Q05_us = NaN(numel(classes),1);
Q95_us = NaN(numel(classes),1);

for k = 1:numel(classes)

    m = ...
        string(referenceEvents.CommandClass)==classes(k) & ...
        isfinite(referenceEvents.Delay_us);

    d = referenceEvents.Delay_us(m);

    NReferenceEvents(k) = numel(d);

    if ~isempty(d)

        MedianDelay_us(k) = median(d);
        RobustSD_us(k) = robustSigma(d);
        Q05_us(k) = percentileLocal(d,5);
        Q95_us(k) = percentileLocal(d,95);
    end
end

DelayPriors = table( ...
    TransitionClass, ...
    NReferenceEvents, ...
    MedianDelay_us, ...
    RobustSD_us, ...
    Q05_us, ...
    Q95_us);

fprintf("\n============================================================\n");
fprintf("OPENXSTIM GRADIENT THRESHOLD ANALYSIS V2\n");
fprintf("============================================================\n");
fprintf("Reference captures: PASS and command <= %.3g mA\n", ...
    cfg.REFERENCE_MAX_COMMAND_CURRENT_mA);
fprintf("\nDelay priors:\n");
disp(DelayPriors);

if any(~isfinite(DelayPriors.MedianDelay_us))
    error("At least one transition class has no usable delay prior.");
end

%% ========================================================================
% MASTER CONTAINERS
% ========================================================================

nCaptures = height(stage1Summary);

switchParts = cell(nCaptures,1);
passiveSampleParts = cell(nCaptures,1);
passivePhaseParts = cell(nCaptures,1);
scaleParts = cell(nCaptures,1);

representative = struct();

%% ========================================================================
% PROCESS RAW CAPTURES
% ========================================================================

for c = 1:nCaptures

    captureID = stage1Summary.CaptureID(c);
    attemptNumber = stage1Summary.AttemptNumber(c);
    commandCurrent_mA = stage1Summary.CommandCurrent_mA(c);
    captureWithinAttempt = stage1Summary.CaptureWithinAttempt(c);

    fprintf("\n------------------------------------------------------------\n");
    fprintf("CAPTURE %d / %d | %.3g mA p-p\n", ...
        c,nCaptures,commandCurrent_mA);
    fprintf("------------------------------------------------------------\n");

    try

        if c>numel(stage1ResultFiles) || ...
                strlength(stage1ResultFiles(c))==0 || ...
                ~isfile(stage1ResultFiles(c))

            error("Stage 1 per-capture MAT file is missing.");
        end

        S = load(stage1ResultFiles(c));

        if ~isfield(S,"result")
            error("Stage 1 per-capture MAT contains no result.");
        end

        R1 = S.result;

        if ~isfield(R1,"selectedCommandTable") || ...
                isempty(R1.selectedCommandTable)

            error("No selected complete Stage 1 packet.");
        end

        commands = R1.selectedCommandTable;
        csvPath = string(R1.csvPath);

        if ~isfile(csvPath)
            error("Raw CSV not found: %s",csvPath);
        end

        [data,t,~,Ts,~] = loadRigolMemoryCSV(csvPath);

        Fs = 1/Ts;

        outputV = data(:,cfg.OUTPUT_CHANNEL);
        Iraw = 1000*outputV/cfg.R_LOAD_OHM;

        smoothSamples = ...
            max(3,round(cfg.OUTPUT_SMOOTH_US*1e-6/Ts));

        if mod(smoothSamples,2)==0
            smoothSamples = smoothSamples+1;
        end

        Ismooth = movmean(Iraw,smoothSamples);
        grad = gradient(Ismooth,Ts)/1e6;
        absGrad = abs(grad);

        commandTime_s = commands.CommandTime_s(:);
        commandClass = string(commands.TransitionClass(:));
        commandEvent = commands.EventNumberWithinPacket(:);

        nCommands = height(commands);

        %% ----------------------------------------------------------------
        % LOCAL ZERO
        % -----------------------------------------------------------------

        zeroEnd_s = ...
            commandTime_s(1)-cfg.ZERO_BASELINE_GUARD_US*1e-6;

        zeroStart_s = ...
            max( ...
            t(1), ...
            zeroEnd_s-cfg.ZERO_BASELINE_WINDOW_MS*1e-3);

        zeroMask = ...
            t>=zeroStart_s & ...
            t<=zeroEnd_s;

        if nnz(zeroMask)<20
            error("Insufficient local zero baseline.");
        end

        zeroLevel_mA = ...
            median(Iraw(zeroMask),'omitnan');

        gradientNoiseSD_mA_per_us = ...
            robustSigma(grad(zeroMask));

        %% ----------------------------------------------------------------
        % MEASURED PEAK-TO-PEAK CURRENT
        % -----------------------------------------------------------------

        responseStart_s = ...
            max( ...
            t(1), ...
            commandTime_s(1) ...
            - cfg.RESPONSE_SEARCH_BEFORE_FIRST_COMMAND_MS*1e-3);

        responseEnd_s = ...
            min( ...
            t(end), ...
            commandTime_s(end) ...
            + cfg.RESPONSE_SEARCH_AFTER_LAST_COMMAND_MS*1e-3);

        responseMask = ...
            t>=responseStart_s & ...
            t<=responseEnd_s;

        localI = Iraw(responseMask);

        positiveLevel_mA = ...
            percentileLocal( ...
            localI, ...
            cfg.POSITIVE_LEVEL_PERCENTILE);

        negativeLevel_mA = ...
            percentileLocal( ...
            localI, ...
            cfg.NEGATIVE_LEVEL_PERCENTILE);

        positiveHalf_mA = ...
            positiveLevel_mA-zeroLevel_mA;

        negativeHalf_mA = ...
            zeroLevel_mA-negativeLevel_mA;

        measuredIpp_mA = ...
            positiveLevel_mA-negativeLevel_mA;

        if ~isfinite(measuredIpp_mA) || measuredIpp_mA<=0
            error("Invalid measured p-p current.");
        end

        %% ----------------------------------------------------------------
        % GUIDED SWITCHING EDGES
        % -----------------------------------------------------------------

        expectedCentre_s = NaN(nCommands,1);
        priorDelay_us = NaN(nCommands,1);
        expectedDirection = NaN(nCommands,1);

        for e = 1:nCommands

            p = find( ...
                DelayPriors.TransitionClass==commandClass(e), ...
                1);

            priorDelay_us(e) = ...
                DelayPriors.MedianDelay_us(p);

            expectedCentre_s(e) = ...
                commandTime_s(e) ...
                + priorDelay_us(e)*1e-6;

            expectedDirection(e) = ...
                transitionDirection(commandClass(e));
        end

        responseTime_s = NaN(nCommands,1);
        measuredDelay_us = NaN(nCommands,1);
        signedGradient_mA_per_us = NaN(nCommands,1);
        absGradient_mA_per_us = NaN(nCommands,1);
        expectedPhysicalStep_mA = NaN(nCommands,1);
        normGradientByIpp_per_us = NaN(nCommands,1);
        normGradientByExpectedStep_per_us = NaN(nCommands,1);
        searchStart_s = NaN(nCommands,1);
        searchEnd_s = NaN(nCommands,1);

        for e = 1:nCommands

            lo = ...
                expectedCentre_s(e) ...
                - cfg.GUIDED_SEARCH_HALF_WIDTH_US*1e-6;

            hi = ...
                expectedCentre_s(e) ...
                + cfg.GUIDED_SEARCH_HALF_WIDTH_US*1e-6;

            if e>1

                lo = max( ...
                    lo, ...
                    0.5*( ...
                    expectedCentre_s(e-1) ...
                    + expectedCentre_s(e)));
            end

            if e<nCommands

                hi = min( ...
                    hi, ...
                    0.5*( ...
                    expectedCentre_s(e) ...
                    + expectedCentre_s(e+1)));
            end

            lo = max(lo,responseStart_s);
            hi = min(hi,responseEnd_s);

            searchStart_s(e) = lo;
            searchEnd_s(e) = hi;

            m = ...
                t>=lo & ...
                t<=hi & ...
                sign(grad)==expectedDirection(e);

            idx = find(m);

            if isempty(idx)
                continue;
            end

            [~,ii] = max(absGrad(idx));

            edgeIdx = idx(ii);

            responseTime_s(e) = t(edgeIdx);

            measuredDelay_us(e) = ...
                (responseTime_s(e)-commandTime_s(e))*1e6;

            signedGradient_mA_per_us(e) = grad(edgeIdx);
            absGradient_mA_per_us(e) = absGrad(edgeIdx);

            expectedPhysicalStep_mA(e) = ...
                expectedPhysicalStep( ...
                commandClass(e), ...
                positiveHalf_mA, ...
                negativeHalf_mA, ...
                measuredIpp_mA);

            normGradientByIpp_per_us(e) = ...
                absGradient_mA_per_us(e)/measuredIpp_mA;

            normGradientByExpectedStep_per_us(e) = ...
                absGradient_mA_per_us(e) ...
                / expectedPhysicalStep_mA(e);
        end

        isBipolar = ...
            commandClass=="pos_to_neg" | ...
            commandClass=="neg_to_pos";

        SwitchEdgesThisCapture = table( ...
            repmat(captureID,nCommands,1), ...
            repmat(attemptNumber,nCommands,1), ...
            repmat(commandCurrent_mA,nCommands,1), ...
            repmat(captureWithinAttempt,nCommands,1), ...
            commandEvent, ...
            commandClass, ...
            isBipolar, ...
            commandTime_s, ...
            priorDelay_us, ...
            expectedCentre_s, ...
            searchStart_s, ...
            searchEnd_s, ...
            responseTime_s, ...
            measuredDelay_us, ...
            expectedDirection, ...
            signedGradient_mA_per_us, ...
            absGradient_mA_per_us, ...
            repmat(measuredIpp_mA,nCommands,1), ...
            expectedPhysicalStep_mA, ...
            normGradientByIpp_per_us, ...
            normGradientByExpectedStep_per_us, ...
            'VariableNames',{ ...
            'CaptureID', ...
            'AttemptNumber', ...
            'CommandCurrent_mA', ...
            'CaptureWithinAttempt', ...
            'CommandEvent', ...
            'TransitionClass', ...
            'IsBipolar', ...
            'CommandTime_s', ...
            'ReferenceDelay_us', ...
            'ExpectedResponseCentre_s', ...
            'SearchStart_s', ...
            'SearchEnd_s', ...
            'GuidedResponseTime_s', ...
            'GuidedDelay_us', ...
            'ExpectedGradientDirection', ...
            'SignedGradient_mA_per_us', ...
            'AbsGradient_mA_per_us', ...
            'MeasuredIpp_mA', ...
            'ExpectedPhysicalStep_mA', ...
            'NormGradientByIpp_per_us', ...
            'NormGradientByExpectedStep_per_us'});

        switchParts{c} = SwitchEdgesThisCapture;

        %% ----------------------------------------------------------------
        % PHASE-BY-PHASE PASSIVE ANALYSIS
        % -----------------------------------------------------------------

        validEdges = ...
            isfinite(responseTime_s);

        if nnz(validEdges)~=nCommands

            warning( ...
                "Capture %d guided edges: %d / %d.", ...
                captureID,nnz(validEdges),nCommands);
        end

        % We expect all 41 from the current dataset. If an edge is missing,
        % save switch data but skip phase analysis for this capture.
        if nnz(validEdges)<2

            warning("Capture %d has too few guided edges for phases.",captureID);
            continue;
        end

        guard_s = ...
            cfg.PASSIVE_EDGE_GUARD_US*1e-6;

        passiveDtSamples = ...
            max(1,round(cfg.PASSIVE_SAMPLE_DT_US*1e-6/Ts));

        nPotentialPhases = nCommands-1;

        phaseRows = cell(nPotentialPhases,1);
        passiveSampleTables = cell(nPotentialPhases,1);

        for p = 1:nPotentialPhases

            if ~isfinite(responseTime_s(p)) || ...
                    ~isfinite(responseTime_s(p+1))

                continue;
            end

            phaseStart_s = responseTime_s(p);
            phaseEnd_s = responseTime_s(p+1);

            passiveStart_s = phaseStart_s+guard_s;
            passiveEnd_s = phaseEnd_s-guard_s;

            if passiveEnd_s<=passiveStart_s
                continue;
            end

            pm = ...
                t>=passiveStart_s & ...
                t<=passiveEnd_s;

            pidx = find(pm);

            if numel(pidx)<10
                continue;
            end

            passiveAbs = absGrad(pidx);

            [phaseMaxRaw,iiMax] = max(passiveAbs);

            phaseMaxIdx = pidx(iiMax);
            phaseMaxTime_s = t(phaseMaxIdx);

            phaseQ99Raw = percentileLocal(passiveAbs,99);
            phaseMedianRaw = median(passiveAbs,'omitnan');

            earlyEnd_s = min( ...
                passiveEnd_s, ...
                passiveStart_s ...
                + cfg.EARLY_PASSIVE_WINDOW_US*1e-6);

            earlyMask = ...
                t>=passiveStart_s & ...
                t<=earlyEnd_s;

            earlyIdx = find(earlyMask);

            if isempty(earlyIdx)

                earlyMaxRaw = NaN;
                earlyMaxTime_s = NaN;

            else

                [earlyMaxRaw,iiEarly] = ...
                    max(absGrad(earlyIdx));

                earlyMaxTime_s = ...
                    t(earlyIdx(iiEarly));
            end

            phaseRows{p} = table( ...
                captureID, ...
                attemptNumber, ...
                commandCurrent_mA, ...
                captureWithinAttempt, ...
                p, ...
                commandClass(p), ...
                commandClass(p+1), ...
                phaseStart_s, ...
                phaseEnd_s, ...
                passiveStart_s, ...
                passiveEnd_s, ...
                (phaseEnd_s-phaseStart_s)*1e6, ...
                phaseMaxTime_s, ...
                phaseMaxRaw, ...
                phaseMaxRaw/measuredIpp_mA, ...
                phaseQ99Raw, ...
                phaseQ99Raw/measuredIpp_mA, ...
                phaseMedianRaw, ...
                phaseMedianRaw/measuredIpp_mA, ...
                earlyMaxTime_s, ...
                earlyMaxRaw, ...
                earlyMaxRaw/measuredIpp_mA, ...
                measuredIpp_mA, ...
                'VariableNames',{ ...
                'CaptureID', ...
                'AttemptNumber', ...
                'CommandCurrent_mA', ...
                'CaptureWithinAttempt', ...
                'PhysicalPhase', ...
                'StartTransitionClass', ...
                'EndTransitionClass', ...
                'PhaseStart_s', ...
                'PhaseEnd_s', ...
                'PassiveStart_s', ...
                'PassiveEnd_s', ...
                'PhaseDuration_us', ...
                'PassiveMaxTime_s', ...
                'PassiveMaxAbsGradient_mA_per_us', ...
                'PassiveMaxNormByIpp_per_us', ...
                'PassiveQ99AbsGradient_mA_per_us', ...
                'PassiveQ99NormByIpp_per_us', ...
                'PassiveMedianAbsGradient_mA_per_us', ...
                'PassiveMedianNormByIpp_per_us', ...
                'EarlyPassiveMaxTime_s', ...
                'EarlyPassiveMaxAbsGradient_mA_per_us', ...
                'EarlyPassiveMaxNormByIpp_per_us', ...
                'MeasuredIpp_mA'});

            sampleIdx = pidx(1:passiveDtSamples:end);

            passiveSampleTables{p} = table( ...
                repmat(captureID,numel(sampleIdx),1), ...
                repmat(commandCurrent_mA,numel(sampleIdx),1), ...
                repmat(p,numel(sampleIdx),1), ...
                t(sampleIdx), ...
                absGrad(sampleIdx), ...
                absGrad(sampleIdx)/measuredIpp_mA, ...
                'VariableNames',{ ...
                'CaptureID', ...
                'CommandCurrent_mA', ...
                'PhysicalPhase', ...
                'Time_s', ...
                'AbsGradient_mA_per_us', ...
                'NormGradientByIpp_per_us'});
        end

        phaseRows = ...
            phaseRows(~cellfun(@isempty,phaseRows));

        passiveSampleTables = ...
            passiveSampleTables(~cellfun(@isempty,passiveSampleTables));

        if ~isempty(phaseRows)
            passivePhaseParts{c} = vertcat(phaseRows{:});
        end

        if ~isempty(passiveSampleTables)
            passiveSampleParts{c} = vertcat(passiveSampleTables{:});
        end

        %% ----------------------------------------------------------------
        % CURRENT-SCALE TABLE
        % -----------------------------------------------------------------

        scaleParts{c} = table( ...
            captureID, ...
            attemptNumber, ...
            commandCurrent_mA, ...
            captureWithinAttempt, ...
            Fs/1e6, ...
            zeroLevel_mA, ...
            positiveLevel_mA, ...
            negativeLevel_mA, ...
            positiveHalf_mA, ...
            negativeHalf_mA, ...
            measuredIpp_mA, ...
            measuredIpp_mA/commandCurrent_mA, ...
            gradientNoiseSD_mA_per_us, ...
            'VariableNames',{ ...
            'CaptureID', ...
            'AttemptNumber', ...
            'CommandCurrent_mA', ...
            'CaptureWithinAttempt', ...
            'Fs_MSa_s', ...
            'ZeroLevel_mA', ...
            'PositiveLevel_mA', ...
            'NegativeLevel_mA', ...
            'PositiveHalfMagnitude_mA', ...
            'NegativeHalfMagnitude_mA', ...
            'MeasuredIpp_mA', ...
            'MeasuredToCommandPPRatio', ...
            'GradientNoiseSD_mA_per_us'});

        %% ----------------------------------------------------------------
        % REPRESENTATIVE CAPTURE FOR FIGURE 4
        % -----------------------------------------------------------------

        key = ...
            matlab.lang.makeValidName( ...
            sprintf("I_%g_mA",commandCurrent_mA));

        if ~isfield(representative,key)

            R = struct();

            R.captureID = captureID;
            R.commandCurrent_mA = commandCurrent_mA;
            R.t = t;
            R.Iraw = Iraw;
            R.absGrad = absGrad;
            R.responseStart_s = responseStart_s;
            R.responseEnd_s = responseEnd_s;
            R.switchTimes_s = responseTime_s;
            R.measuredIpp_mA = measuredIpp_mA;

            if ~isempty(passivePhaseParts{c})

                R.passiveMaxTimes_s = ...
                    passivePhaseParts{c}.PassiveMaxTime_s;

                R.passiveMaxGrad = ...
                    passivePhaseParts{c}.PassiveMaxAbsGradient_mA_per_us;

                R.earlyPassiveMaxTimes_s = ...
                    passivePhaseParts{c}.EarlyPassiveMaxTime_s;

                R.earlyPassiveMaxGrad = ...
                    passivePhaseParts{c}.EarlyPassiveMaxAbsGradient_mA_per_us;

            else

                R.passiveMaxTimes_s = [];
                R.passiveMaxGrad = [];
                R.earlyPassiveMaxTimes_s = [];
                R.earlyPassiveMaxGrad = [];
            end

            representative.(key) = R;
        end

        fprintf("Measured Ipp               : %.6f mA\n",measuredIpp_mA);
        fprintf("Measured / command p-p     : %.6f\n", ...
            measuredIpp_mA/commandCurrent_mA);
        fprintf("Guided switch edges        : %d / %d\n", ...
            nnz(validEdges),nCommands);

        if ~isempty(passivePhaseParts{c})

            fprintf("Passive physical phases    : %d\n", ...
                height(passivePhaseParts{c}));

            fprintf("Median phase max |dI/dt|   : %.6f mA/us\n", ...
                median( ...
                passivePhaseParts{c}.PassiveMaxAbsGradient_mA_per_us, ...
                'omitnan'));

            fprintf("Maximum phase max |dI/dt|  : %.6f mA/us\n", ...
                max( ...
                passivePhaseParts{c}.PassiveMaxAbsGradient_mA_per_us, ...
                [], ...
                'omitnan'));
        end

        clear data t outputV Iraw Ismooth grad absGrad

    catch ME

        fprintf(2,"Capture %d analysis failed: %s\n",captureID,ME.message);
    end
end

%% ========================================================================
% COMBINE TABLES
% ========================================================================

switchParts = switchParts(~cellfun(@isempty,switchParts));

if isempty(switchParts)
    SwitchEdges = table();
else
    SwitchEdges = vertcat(switchParts{:});
end

passivePhaseParts = passivePhaseParts(~cellfun(@isempty,passivePhaseParts));

if isempty(passivePhaseParts)
    PassivePhases = table();
else
    PassivePhases = vertcat(passivePhaseParts{:});
end

passiveSampleParts = passiveSampleParts(~cellfun(@isempty,passiveSampleParts));

