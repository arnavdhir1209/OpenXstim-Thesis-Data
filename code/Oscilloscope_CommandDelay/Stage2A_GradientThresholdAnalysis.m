function d = transitionDirection(type)

    switch string(type)

        case "zero_to_pos"
            d = +1;

        case "pos_to_neg"
            d = -1;

        case "neg_to_pos"
            d = +1;

        case "neg_to_zero"
            d = +1;

        otherwise
            d = NaN;
    end
end

function step = expectedPhysicalStep( ...
    type,positiveHalf,negativeHalf,measuredIpp)

    switch string(type)

        case "zero_to_pos"
            step = positiveHalf;

        case {"pos_to_neg","neg_to_pos"}
            step = measuredIpp;

        case "neg_to_zero"
            step = negativeHalf;

        otherwise
            step = NaN;
    end
end

function sigma = robustSigma(x)

    x = x(isfinite(x));

    if isempty(x)
        sigma = NaN;
        return;
    end

    med = median(x);

    sigma = 1.4826*median(abs(x-med));

    if ~isfinite(sigma) || sigma<=0
        sigma = std(x);
    end
end

function q = percentileLocal(x,p)

    x = sort(x(isfinite(x)));

    if isempty(x)
        q = NaN;
        return;
    end

    if isscalar(x)
        q = x;
        return;
    end

    r = 1+(p/100)*(numel(x)-1);

    lo = floor(r);
    hi = ceil(r);

    if lo==hi
        q = x(lo);
    else
        q = x(lo)+(r-lo)*(x(hi)-x(lo));
    end
end

function y = thresholdMidpoint(a,b,mode)

    switch lower(string(mode))

        case "arithmetic"
            y = 0.5*(a+b);

        case "geometric"

            if a>0 && b>0
                y = sqrt(a*b);
            else
                y = NaN;
            end

        otherwise
            error("Unknown threshold midpoint mode.");
    end
end

function [data,t,t0,Ts,header] = loadRigolMemoryCSV(path)

    fid = fopen(path,'r');

    if fid<0
        error("Could not open CSV.");
    end

    cleanup = onCleanup(@() fclose(fid));

    header = fgetl(fid);

    tok = regexp( ...
        header, ...
        't0\s*=\s*([+-]?\d*\.?\d+(?:[eE][+-]?\d+)?)', ...
        'tokens','once');

    if isempty(tok)
        error("Could not parse t0.");
    end

    t0 = str2double(tok{1});

    tok = regexp( ...
        header, ...
        'tInc\s*=\s*([+-]?\d*\.?\d+(?:[eE][+-]?\d+)?)', ...
        'tokens','once');

    if isempty(tok)
        error("Could not parse tInc.");
    end

    Ts = str2double(tok{1});

    data = readmatrix(path,'NumHeaderLines',1);

    data(:,all(~isfinite(data),1)) = [];
    data = data(any(isfinite(data),2),:);

    t = t0+(0:size(data,1)-1).'*Ts;
end

