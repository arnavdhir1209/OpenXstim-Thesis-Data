function summary = OpenXstimPassive_BuildSummaries( ...
    modelTime_us,currentModel_mA,normalizedModel,chargeModel_uC,M)
% Build Stage 4 current, polarity, regime and mean-waveform summaries.

valid = M.ValidPhase;

currents = unique(M.CommandCurrent_mA(valid));

%% ========================================================================
% CURRENT SUMMARY
% ========================================================================

n = numel(currents);

CommandCurrent_mA = currents;

NPhases = zeros(n,1);
NValid = zeros(n,1);

MeanReferenceCurrent_mA = NaN(n,1);
SDReferenceCurrent_mA = NaN(n,1);

MeanEndNormalized = NaN(n,1);
SDEndNormalized = NaN(n,1);

MeanCurrentLoss_pct = NaN(n,1);
SDCurrentLoss_pct = NaN(n,1);

MeanEarlySlope_per_ms = NaN(n,1);
MeanMaxCollapseRate_per_ms = NaN(n,1);

FractionCrossing90 = NaN(n,1);
FractionCrossing75 = NaN(n,1);
FractionCrossing50 = NaN(n,1);
FractionCrossing25 = NaN(n,1);

MedianTimeTo50_us = NaN(n,1);
MedianChargeTo50_uC = NaN(n,1);

MeanTerminalCharge_uC = NaN(n,1);
MeanEstimatedDeltaVcEnd_V = NaN(n,1);

FractionDroopOnly = NaN(n,1);
FractionPartialCollapse = NaN(n,1);
FractionStrongCollapse = NaN(n,1);

for k = 1:n

    a = M.CommandCurrent_mA==currents(k);
    v = a & valid;

    NPhases(k) = nnz(a);
    NValid(k) = nnz(v);

    MeanReferenceCurrent_mA(k) = ...
        mean(M.ReferenceCurrent_mA(v),'omitnan');

    SDReferenceCurrent_mA(k) = ...
        std(M.ReferenceCurrent_mA(v),'omitnan');

    MeanEndNormalized(k) = ...
        mean(M.EndNormalized(v),'omitnan');

    SDEndNormalized(k) = ...
        std(M.EndNormalized(v),'omitnan');

    MeanCurrentLoss_pct(k) = ...
        mean(M.CurrentLoss_pct(v),'omitnan');

    SDCurrentLoss_pct(k) = ...
        std(M.CurrentLoss_pct(v),'omitnan');

    MeanEarlySlope_per_ms(k) = ...
        mean(M.EarlySlope_per_ms(v),'omitnan');

    MeanMaxCollapseRate_per_ms(k) = ...
        mean(M.MaxCollapseRate_per_ms(v),'omitnan');

    FractionCrossing90(k) = ...
        mean(isfinite(M.TimeTo90_us(v)));

    FractionCrossing75(k) = ...
        mean(isfinite(M.TimeTo75_us(v)));

    FractionCrossing50(k) = ...
        mean(isfinite(M.TimeTo50_us(v)));

    FractionCrossing25(k) = ...
        mean(isfinite(M.TimeTo25_us(v)));

    MedianTimeTo50_us(k) = ...
        median(M.TimeTo50_us(v),'omitnan');

    MedianChargeTo50_uC(k) = ...
        median(M.ChargeTo50_uC(v),'omitnan');

    MeanTerminalCharge_uC(k) = ...
        mean(M.TerminalCharge_uC(v),'omitnan');

    MeanEstimatedDeltaVcEnd_V(k) = ...
        mean(M.EstimatedDeltaVcEnd_V(v),'omitnan');

    FractionDroopOnly(k) = ...
        mean(M.PassiveRegime(v)=="DROOP_ONLY");

    FractionPartialCollapse(k) = ...
        mean(M.PassiveRegime(v)=="PARTIAL_COLLAPSE");

    FractionStrongCollapse(k) = ...
        mean(M.PassiveRegime(v)=="STRONG_COLLAPSE");
end

CurrentSummary = table( ...
    CommandCurrent_mA, ...
    NPhases, ...
    NValid, ...
    MeanReferenceCurrent_mA, ...
    SDReferenceCurrent_mA, ...
    MeanEndNormalized, ...
    SDEndNormalized, ...
    MeanCurrentLoss_pct, ...
    SDCurrentLoss_pct, ...
    MeanEarlySlope_per_ms, ...
    MeanMaxCollapseRate_per_ms, ...
    FractionCrossing90, ...
    FractionCrossing75, ...
    FractionCrossing50, ...
    FractionCrossing25, ...
    MedianTimeTo50_us, ...
    MedianChargeTo50_uC, ...
    MeanTerminalCharge_uC, ...
    MeanEstimatedDeltaVcEnd_V, ...
    FractionDroopOnly, ...
    FractionPartialCollapse, ...
    FractionStrongCollapse);

%% ========================================================================
% POLARITY SUMMARY
% ========================================================================

polarities = ["positive";"negative"];

rows = cell(numel(currents)*2,1);
r = 0;

for k = 1:numel(currents)

    for p = 1:numel(polarities)

        r = r+1;

        m = ...
            valid & ...
            M.CommandCurrent_mA==currents(k) & ...
            M.Polarity==polarities(p);

        rows{r} = table( ...
            currents(k), ...
            polarities(p), ...
            nnz(m), ...
            mean(M.ReferenceCurrent_mA(m),'omitnan'), ...
            mean(M.EndNormalized(m),'omitnan'), ...
            std(M.EndNormalized(m),'omitnan'), ...
            mean(M.CurrentLoss_pct(m),'omitnan'), ...
            mean(M.EarlySlope_per_ms(m),'omitnan'), ...
            mean(M.MaxCollapseRate_per_ms(m),'omitnan'), ...
            'VariableNames',{ ...
            'CommandCurrent_mA', ...
            'Polarity', ...
            'NPhases', ...
            'MeanReferenceCurrent_mA', ...
            'MeanEndNormalized', ...
            'SDEndNormalized', ...
            'MeanCurrentLoss_pct', ...
            'MeanEarlySlope_per_ms', ...
            'MeanMaxCollapseRate_per_ms'});
    end
end

PolaritySummary = vertcat(rows{:});

%% ========================================================================
% REGIME SUMMARY
% ========================================================================

regimes = [ ...
    "DROOP_ONLY"; ...
    "PARTIAL_COLLAPSE"; ...
    "STRONG_COLLAPSE"];

rows = cell(numel(currents)*numel(regimes),1);
r = 0;

for k = 1:numel(currents)

    for q = 1:numel(regimes)

        r = r+1;

        m = ...
            valid & ...
            M.CommandCurrent_mA==currents(k) & ...
            M.PassiveRegime==regimes(q);

        rows{r} = table( ...
            currents(k), ...
            regimes(q), ...
            nnz(m), ...
            'VariableNames',{ ...
            'CommandCurrent_mA', ...
            'PassiveRegime', ...
            'NPhases'});
    end
end

RegimeSummary = vertcat(rows{:});

%% ========================================================================
% MEAN WAVEFORMS
% ========================================================================

rows = cell(numel(currents)*2,1);
r = 0;

for k = 1:numel(currents)

    for p = 1:numel(polarities)

        m = ...
            valid & ...
            M.CommandCurrent_mA==currents(k) & ...
            M.Polarity==polarities(p);

        if ~any(m)
            continue;
        end

        r = r+1;

        rows{r} = table( ...
            repmat(currents(k),numel(modelTime_us),1), ...
            repmat(polarities(p),numel(modelTime_us),1), ...
            modelTime_us, ...
            mean(currentModel_mA(:,m),2,'omitnan'), ...
            std(currentModel_mA(:,m),0,2,'omitnan'), ...
            mean(normalizedModel(:,m),2,'omitnan'), ...
            std(normalizedModel(:,m),0,2,'omitnan'), ...
            mean(chargeModel_uC(:,m),2,'omitnan'), ...
            sum(isfinite(normalizedModel(:,m)),2), ...
            'VariableNames',{ ...
            'CommandCurrent_mA', ...
            'Polarity', ...
            'Time_us', ...
            'MeanCurrent_mA', ...
            'SDCurrent_mA', ...
            'MeanNormalized', ...
            'SDNormalized', ...
            'MeanCharge_uC', ...
            'NFinite'});
    end
end

rows = rows(~cellfun(@isempty,rows));
MeanWaveforms = vertcat(rows{:});

%% ========================================================================
% STRUCTURED VIEW
% ========================================================================

ByCurrent = struct();

for k = 1:numel(currents)

    Icmd = currents(k);

    m = valid & M.CommandCurrent_mA==Icmd;

    fieldName = ...
        matlab.lang.makeValidName(sprintf("I_%g_mA",Icmd));

    G = struct();

    G.commandCurrent_mA = Icmd;
    G.N = nnz(m);
    G.phaseRows = find(m);

    G.meanCurrent_mA = ...
        mean(currentModel_mA(:,m),2,'omitnan');

    G.meanNormalized = ...
        mean(normalizedModel(:,m),2,'omitnan');

    G.sdNormalized = ...
        std(normalizedModel(:,m),0,2,'omitnan');

    G.meanCharge_uC = ...
        mean(chargeModel_uC(:,m),2,'omitnan');

    ByCurrent.(fieldName) = G;
end

%% ========================================================================
% OUTPUT
% ========================================================================

summary = struct();

summary.CurrentSummary = CurrentSummary;
summary.PolaritySummary = PolaritySummary;
summary.RegimeSummary = RegimeSummary;
summary.MeanWaveforms = MeanWaveforms;
summary.ByCurrent = ByCurrent;

end
