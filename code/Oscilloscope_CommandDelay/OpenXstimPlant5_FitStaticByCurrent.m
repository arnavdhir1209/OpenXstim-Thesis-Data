function O = OpenXstimPlant5_FitStaticByCurrent(CaptureSummary,cfg)
% OpenXstimPlant5_FitStaticByCurrent
%
% Stage 5 does NOT fit a cross-current static law. It simply characterizes
% the measured early peak-to-peak current independently at each command.
% Stage 6 will later decide whether a gain, polynomial or lookup table is the
% appropriate unified static mapping.

required = [ ...
    "CaptureID", ...
    "CommandCurrent_mA", ...
    "CaptureWithinAttempt", ...
    "MeanEarlyMeasuredIpp_mA"];

if ~all(ismember(required,string(CaptureSummary.Properties.VariableNames)))
    error("CaptureSummary is missing fields required by revised Stage 5 static analysis.");
end

C = CaptureSummary;

valid = ...
    isfinite(C.CaptureID) & ...
    isfinite(C.CommandCurrent_mA) & ...
    isfinite(C.MeanEarlyMeasuredIpp_mA) & ...
    ~ismember(C.CaptureID,cfg.EXCLUDE_CAPTURE_IDS);

C = C(valid,:);

MeasuredToCommandRatio = ...
    C.MeanEarlyMeasuredIpp_mA ./ C.CommandCurrent_mA;

captureTable = table( ...
    C.CaptureID, ...
    C.CommandCurrent_mA, ...
    C.CaptureWithinAttempt, ...
    C.MeanEarlyMeasuredIpp_mA, ...
    MeasuredToCommandRatio, ...
    'VariableNames',{ ...
    'CaptureID', ...
    'CommandCurrent_mA', ...
    'CaptureWithinAttempt', ...
    'MeasuredEarlyIpp_mA', ...
    'MeasuredToCommandRatio'});

currents = cfg.COMMAND_CURRENTS_mApp(:);

parts = cell(numel(currents),1);

for k = 1:numel(currents)

    I = currents(k);

    m = captureTable.CommandCurrent_mA==I;

    x = captureTable.MeasuredEarlyIpp_mA(m);
    r = captureTable.MeasuredToCommandRatio(m);

    n = nnz(m);

    if n==0

        parts{k} = table( ...
            I,0,NaN,NaN,NaN,NaN,NaN,NaN,NaN, ...
            'VariableNames',{ ...
            'CommandCurrent_mA','N', ...
            'MeanMeasuredIpp_mA','SDMeasuredIpp_mA','MedianMeasuredIpp_mA', ...
            'MeanScaleRatio','SDScaleRatio','MedianScaleRatio','RobustSDScaleRatio'});

        continue;
    end

    parts{k} = table( ...
        I, ...
        n, ...
        mean(x,'omitnan'), ...
        std(x,'omitnan'), ...
        median(x,'omitnan'), ...
        mean(r,'omitnan'), ...
        std(r,'omitnan'), ...
        median(r,'omitnan'), ...
        robustSD(r), ...
        'VariableNames',{ ...
        'CommandCurrent_mA','N', ...
        'MeanMeasuredIpp_mA','SDMeasuredIpp_mA','MedianMeasuredIpp_mA', ...
        'MeanScaleRatio','SDScaleRatio','MedianScaleRatio','RobustSDScaleRatio'});
end

currentSummary = vertcat(parts{:});

O = struct();
O.captureTable = captureTable;
O.currentSummary = currentSummary;
O.note = "Per-current characterization only. Cross-current static-law fitting is deferred to Stage 6.";

end

function s = robustSD(x)

x = x(isfinite(x));

if isempty(x)
    s = NaN;
    return;
end

med = median(x);
s = 1.4826*median(abs(x-med));

end
