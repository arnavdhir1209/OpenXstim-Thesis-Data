function Stage7_BuildOpenXstimHybrid()
% Stage7_BuildOpenXstimHybrid
%
% Builds and saves a single hybrid / gain-scheduled Simulink model for the
% OpenXstim plant, based on the Stage 5, Stage 6 and Stage 6A conclusions.
%
% IMPORTANT
% ---------
% This is a Stage 7 PROTOTYPE / architecture model for presentation and
% refinement. The architecture is evidence-based, but the final Simulink
% validation still needs to compare complete simulated waveforms against
% held-out experimental captures before controller tuning.
%
% Evidence carried into this model:
%   1) Static scale:
%        empirical quadratic calibration through origin
%        Ipp_meas = 0.976727072*Ipp_cmd - 0.00123911627*Ipp_cmd^2
%
%   2) Delay:
%        firmware-transition-class specific
%        + physical FULL_REVERSAL / NEAR_ZERO_START regime flag
%        literal startup kept separate
%
%   3) Fast dynamics:
%        current-specific local Stage 5 models retained
%        no forced common fast transfer function
%
%   4) Ordinary droop:
%        one common linear law
%        k = 0.1619251 /ms
%
%   5) Compliance collapse:
%        state/current-dependent
%        local Stage 5 laws retained at 20, 30 and 50 mA p-p
%        no universal collapse curve is forced
%
% Model input convention
% ----------------------
% The top-level input is a SIGNED PHASE COMMAND in mA.
% For a symmetric bipolar command:
%       Ipp_cmd = 2*abs(Iphase_cmd)
%
% Example:
%       +25 / -25 mA phase command corresponds to 50 mA p-p.
%
% Output
% ------
%   Stage7_OpenXstimHybrid.slx
%
% MATLAB / Simulink
% -----------------
% Designed for standard Simulink + MATLAB Function blocks.
%
% Thesis Stage 7 prototype.

clc;

%% ========================================================================
% USER SETTINGS
% ========================================================================

modelName = "Stage7_OpenXstimHybrid";

% Fast dynamics are around 4-6 us, so use a sub-microsecond fixed step.
Ts = 0.25e-6;     % s
stopTime = 8e-3;  % s

% Default demonstration source: +/- 25 mA phase command = 50 mA p-p.
demoPhaseAmplitude_mA = 25;
demoPeriod_s = 4e-3;
demoPulseWidth_percent = 50;
demoPhaseDelay_s = 0.5e-3;

%% ========================================================================
% CREATE MODEL
% ========================================================================

if bdIsLoaded(modelName)
    close_system(modelName,0);
end

if isfile(modelName + ".slx")
    delete(modelName + ".slx");
end

new_system(modelName);
open_system(modelName);

set_param(modelName, ...
    'SolverType','Fixed-step', ...
    'Solver','FixedStepDiscrete', ...
    'FixedStep',num2str(Ts,'%.15g'), ...
    'StopTime',num2str(stopTime,'%.15g'), ...
    'SaveTime','on', ...
    'TimeSaveName','tout', ...
    'SignalLogging','on', ...
    'SignalLoggingName','logsout');

%% ========================================================================
% TOP-LEVEL TEST HARNESS
% ========================================================================

add_block( ...
    'simulink/Sources/Pulse Generator', ...
    modelName + "/Demo bipolar command", ...
    'Position',[45 150 135 200]);

set_param(modelName + "/Demo bipolar command", ...
    'Amplitude',num2str(2*demoPhaseAmplitude_mA), ...
    'Period',num2str(demoPeriod_s,'%.15g'), ...
    'PulseWidth',num2str(demoPulseWidth_percent), ...
    'PhaseDelay',num2str(demoPhaseDelay_s,'%.15g'));

add_block( ...
    'simulink/Math Operations/Bias', ...
    modelName + "/Centre about zero", ...
    'Position',[175 155 250 195]);

set_param(modelName + "/Centre about zero", ...
    'Bias',num2str(-demoPhaseAmplitude_mA));

plantPath = modelName + "/OpenXstim Hybrid Plant";

add_block( ...
    'simulink/Ports & Subsystems/Subsystem', ...
    plantPath, ...
    'Position',[340 85 620 310]);

% Remove default subsystem contents.
try
    delete_line(plantPath,'In1/1','Out1/1');
catch
end
try
    delete_block(plantPath + "/In1");
catch
end
try
    delete_block(plantPath + "/Out1");
catch
end

add_block( ...
    'simulink/Signal Routing/Mux', ...
    modelName + "/Scope mux", ...
    'Inputs','5', ...
    'Position',[700 125 705 255]);

add_block( ...
    'simulink/Sinks/Scope', ...
    modelName + "/Meeting Scope", ...
    'Position',[770 125 870 255]);

set_param(modelName + "/Meeting Scope", ...
    'NumInputPorts','1');

add_block( ...
    'simulink/Sinks/To Workspace', ...
    modelName + "/Iout workspace", ...
    'Position',[735 300 855 330]);

set_param(modelName + "/Iout workspace", ...
    'VariableName','Stage7_Iout_mA', ...
    'SaveFormat','Timeseries');

add_block( ...
    'simulink/Sinks/To Workspace', ...
    modelName + "/Regime workspace", ...
    'Position',[735 345 855 375]);

set_param(modelName + "/Regime workspace", ...
    'VariableName','Stage7_RegimeCode', ...
    'SaveFormat','Timeseries');

%% ========================================================================
% BUILD HYBRID PLANT SUBSYSTEM
% ========================================================================

% Ports
add_block( ...
    'simulink/Ports & Subsystems/In1', ...
    plantPath + "/Signed phase command mA", ...
    'Position',[25 215 55 235]);

for k = 1:6
    add_block( ...
        'simulink/Ports & Subsystems/Out1', ...
        plantPath + "/Out" + string(k), ...
        'Position',[1130 80+55*(k-1) 1160 100+55*(k-1)]);
    set_param(plantPath + "/Out" + string(k),'Port',num2str(k));
end

set_param(plantPath + "/Out1",'Name','Iout mA');
set_param(plantPath + "/Out2",'Name','Physical regime code');
set_param(plantPath + "/Out3",'Name','Firmware class code');
set_param(plantPath + "/Out4",'Name','Compliance C');
set_param(plantPath + "/Out5",'Name','Oriented charge uC');
set_param(plantPath + "/Out6",'Name','Delayed target mA');

% MATLAB Function blocks
staticBlock = plantPath + "/1 Static calibration";
delayBlock = plantPath + "/2 Transition class + delay";
fastBlock = plantPath + "/3 Scheduled fast dynamics";
droopBlock = plantPath + "/4 Common ordinary droop";
chargeBlock = plantPath + "/5 Continuous charge state";
complianceBlock = plantPath + "/6 Compliance attenuation";

add_block( ...
    'simulink/User-Defined Functions/MATLAB Function', ...
    staticBlock, ...
    'Position',[110 175 275 260]);

add_block( ...
    'simulink/User-Defined Functions/MATLAB Function', ...
    delayBlock, ...
    'Position',[330 140 520 285]);

add_block( ...
    'simulink/User-Defined Functions/MATLAB Function', ...
    fastBlock, ...
    'Position',[575 115 755 220]);

add_block( ...
    'simulink/User-Defined Functions/MATLAB Function', ...
    droopBlock, ...
    'Position',[805 105 965 200]);

add_block( ...
    'simulink/User-Defined Functions/MATLAB Function', ...
    chargeBlock, ...
    'Position',[575 320 755 410]);

add_block( ...
    'simulink/User-Defined Functions/MATLAB Function', ...
    complianceBlock, ...
    'Position',[805 315 965 415]);

add_block( ...
    'simulink/Math Operations/Product', ...
    plantPath + "/Apply compliance", ...
    'Position',[1015 150 1055 200]);

add_block( ...
    'simulink/Discrete/Unit Delay', ...
    plantPath + "/Previous output", ...
    'Position',[1015 455 1065 485]);

set_param(plantPath + "/Previous output", ...
    'SampleTime',num2str(Ts,'%.15g'), ...
    'InitialCondition','0');

% Architecture annotations
Simulink.Annotation(plantPath, ...
    sprintf([ ...
    'STAGE 7 HYBRID PLANT PROTOTYPE\n' ...
    'Stage 6A decision: simplify where supported, retain current/state dependence where reduction loses accuracy.\n' ...
    'Codes: regime 1 = FULL_REVERSAL, 2 = NEAR_ZERO_START, 0 = startup/other.\n' ...
    'Firmware class: 1 = +I->-I, 2 = -I->+I, 3 = -I->0, 4 = 0->nonzero, 0 = hold/other.']));

Simulink.Annotation(plantPath, ...
    sprintf([ ...
    'Static calibration: one common quadratic.\n' ...
    'Fast dynamics: nearest identified current-specific Stage 5 model.\n' ...
    'Ordinary droop: one common linear k = 0.1619251 /ms.\n' ...
    'Compliance: local state-dependent laws retained at 20, 30 and 50 mA p-p.']));

%% ========================================================================
% MATLAB FUNCTION CODE
% ========================================================================

setMATLABFunctionCode(staticBlock, sprintf([ ...
"function [target_mA,Ipp_cmd_mA] = fcn(cmdPhase_mA)\n" ...
"%% Empirical static calibration from Stage 6.\n" ...
"a = 0.976727072;\n" ...
"b = -0.00123911627;\n" ...
"Ipp_cmd_mA = 2*abs(cmdPhase_mA);\n" ...
"scaledIpp = a*Ipp_cmd_mA + b*Ipp_cmd_mA^2;\n" ...
"scaledIpp = max(0,scaledIpp);\n" ...
"if abs(cmdPhase_mA) < 1e-12\n" ...
"    target_mA = 0;\n" ...
"else\n" ...
"    target_mA = sign(cmdPhase_mA)*0.5*scaledIpp;\n" ...
"end\n" ...
"end\n"]));

setMATLABFunctionCode(delayBlock, sprintf([ ...
"function [uDelayed,IppDelayed,classCode,regimeCode] = fcn(u,Ipp,prevIout)\n" ...
"%% Firmware class and physical-regime dependent delay.\n" ...
"%% Fixed simulation sample time must match model Ts.\n" ...
"Ts_us = %.12g;\n" ...
"NBUF = 5000;\n" ...
"persistent uBuf iBuf cBuf rBuf idx prevU activeDelayN activeClass activeRegime\n" ...
"if isempty(idx)\n" ...
"    uBuf = zeros(1,NBUF);\n" ...
"    iBuf = zeros(1,NBUF);\n" ...
"    cBuf = zeros(1,NBUF);\n" ...
"    rBuf = zeros(1,NBUF);\n" ...
"    idx = 1;\n" ...
"    prevU = 0;\n" ...
"    activeDelayN = 0;\n" ...
"    activeClass = 0;\n" ...
"    activeRegime = 0;\n" ...
"end\n" ...
"\n" ...
"changed = abs(u-prevU) > 1e-9;\n" ...
"if changed\n" ...
"    s0 = sign(prevU);\n" ...
"    s1 = sign(u);\n" ...
"\n" ...
"    if s0>0 && s1<0\n" ...
"        activeClass = 1; %% +I -> -I\n" ...
"    elseif s0<0 && s1>0\n" ...
"        activeClass = 2; %% -I -> +I\n" ...
"    elseif s0<0 && s1==0\n" ...
"        activeClass = 3; %% -I -> 0\n" ...
"    elseif s0==0 && s1~=0\n" ...
"        activeClass = 4; %% literal startup\n" ...
"    else\n" ...
"        activeClass = 0;\n" ...
"    end\n" ...
"\n" ...
"    ratio = 1;\n" ...
"    if abs(prevU)>1e-9\n" ...
"        ratio = abs(prevIout)/abs(prevU);\n" ...
"    end\n" ...
"\n" ...
"    if Ipp>=25 && ratio<0.35 && s0~=0\n" ...
"        activeRegime = 2; %% PHYSICAL NEAR_ZERO_START\n" ...
"    elseif s0~=0\n" ...
"        activeRegime = 1; %% FULL_REVERSAL\n" ...
"    else\n" ...
"        activeRegime = 0;\n" ...
"    end\n" ...
"\n" ...
"    delay_us = localDelayUs(activeClass,activeRegime,Ipp);\n" ...
"    activeDelayN = round(delay_us/Ts_us);\n" ...
"    activeDelayN = min(max(activeDelayN,0),NBUF-2);\n" ...
"    prevU = u;\n" ...
"end\n" ...
"\n" ...
"writeIdx = 1 + mod((idx-1)+activeDelayN,NBUF);\n" ...
"uBuf(writeIdx) = u;\n" ...
"iBuf(writeIdx) = Ipp;\n" ...
"cBuf(writeIdx) = activeClass;\n" ...
"rBuf(writeIdx) = activeRegime;\n" ...
"\n" ...
"uDelayed = uBuf(idx);\n" ...
"IppDelayed = iBuf(idx);\n" ...
"classCode = cBuf(idx);\n" ...
"regimeCode = rBuf(idx);\n" ...
"\n" ...
"uBuf(idx) = 0;\n" ...
"iBuf(idx) = 0;\n" ...
"cBuf(idx) = 0;\n" ...
"rBuf(idx) = 0;\n" ...
"idx = 1 + mod(idx,NBUF);\n" ...
"end\n" ...
"\n" ...
"function d = localDelayUs(classCode,regimeCode,Ipp)\n" ...
"%% Stage 5 / Stage 6 timing summary.\n" ...
"if classCode==1\n" ...
"    if regimeCode==2\n" ...
"        d = 970.205; %% high-current physical near-zero +I->-I\n" ...
"    else\n" ...
"        d = 966.09;  %% full-reversal +I->-I\n" ...
"    end\n" ...
"elseif classCode==2\n" ...
"    if regimeCode==2\n" ...
"        d = 990.075; %% high-current physical near-zero -I->+I\n" ...
"    else\n" ...
"        d = 987.66;  %% full-reversal -I->+I\n" ...
"    end\n" ...
"elseif classCode==3\n" ...
"    d = 987.00;      %% -I->0 boundary\n" ...
"elseif classCode==4\n" ...
"    %% Sparse literal startup. Keep separate and use nearest measured mean.\n" ...
"    if Ipp<7.5\n" ...
"        d = 783.75;\n" ...
"    elseif Ipp<12.5\n" ...
"        d = 703.54;\n" ...
"    elseif Ipp<17.5\n" ...
"        d = 749.64;\n" ...
"    elseif Ipp<25\n" ...
"        d = 615.22;\n" ...
"    elseif Ipp<40\n" ...
"        d = 826.05;\n" ...
"    else\n" ...
"        d = 610.03;\n" ...
"    end\n" ...
"else\n" ...
"    d = 0;\n" ...
"end\n" ...
"end\n"], Ts*1e6));

setMATLABFunctionCode(fastBlock, sprintf([ ...
"function y = fcn(u,Ipp,regimeCode)\n" ...
"%% Current-scheduled fast electrical dynamics.\n" ...
"%% Stage 6A rejected both a single common model and a fixed two-regime\n" ...
"%% numerical model, so retain the nearest Stage 5 local model.\n" ...
"Ts = %.15g;\n" ...
"persistent x1 x2 previousFamily\n" ...
"if isempty(x1)\n" ...
"    x1 = 0;\n" ...
"    x2 = 0;\n" ...
"    previousFamily = 2;\n" ...
"end\n" ...
"\n" ...
"[family,wn,zeta,tau] = localFastParameters(Ipp,regimeCode);\n" ...
"\n" ...
"if family~=previousFamily\n" ...
"    x2 = 0;\n" ...
"    previousFamily = family;\n" ...
"end\n" ...
"\n" ...
"if family==1\n" ...
"    %% First order, currently selected only at 50 mA p-p.\n" ...
"    dx = (u-x1)/tau;\n" ...
"    x1 = x1 + Ts*dx;\n" ...
"    x2 = 0;\n" ...
"else\n" ...
"    %% Second-order low-pass with unity DC gain.\n" ...
"    acc = wn^2*(u-x1) - 2*zeta*wn*x2;\n" ...
"    x2 = x2 + Ts*acc;\n" ...
"    x1 = x1 + Ts*x2;\n" ...
"end\n" ...
"\n" ...
"y = x1;\n" ...
"end\n" ...
"\n" ...
"function [family,wn,zeta,tau] = localFastParameters(Ipp,regimeCode)\n" ...
"%% family 2 = SECOND_ORDER, family 1 = FOP.\n" ...
"%% Nearest experimentally identified operating point. No unvalidated\n" ...
"%% interpolation is imposed yet.\n" ...
"family = 2;\n" ...
"tau = 2e-6;\n" ...
"\n" ...
"if Ipp<7.5\n" ...
"    wn = 0.568898e6; zeta = 0.956954;\n" ...
"elseif Ipp<12.5\n" ...
"    wn = 0.692519e6; zeta = 1.00369;\n" ...
"elseif Ipp<17.5\n" ...
"    wn = 0.674360e6; zeta = 0.995379;\n" ...
"elseif Ipp<25\n" ...
"    wn = 0.795394e6; zeta = 1.06549;\n" ...
"elseif Ipp<40\n" ...
"    %% 30 mA local NEAR_ZERO_START model.\n" ...
"    wn = 1.03752e6; zeta = 1.22251;\n" ...
"else\n" ...
"    %% 50 mA local model selected FOP in Stage 5.\n" ...
"    family = 1;\n" ...
"    tau = 1.98195e-6;\n" ...
"    wn = 1; zeta = 1;\n" ...
"end\n" ...
"\n" ...
"%% The regime code is retained explicitly even where the local numerical\n" ...
"%% model is already determined by the measured operating point.\n" ...
"if regimeCode<0\n" ...
"    wn = wn; %% code-generation-safe no-op\n" ...
"end\n" ...
"end\n"], Ts));

setMATLABFunctionCode(droopBlock, sprintf([ ...
"function [y,D] = fcn(x,target)\n" ...
"%% Common ordinary pre-collapse droop selected by Stage 6/6A.\n" ...
"Ts_ms = %.15g;\n" ...
"k = 0.1619251; %% 1/ms\n" ...
"persistent phaseTime_ms previousTarget\n" ...
"if isempty(phaseTime_ms)\n" ...
"    phaseTime_ms = 0;\n" ...
"    previousTarget = 0;\n" ...
"end\n" ...
"\n" ...
"if abs(target-previousTarget)>1e-9\n" ...
"    phaseTime_ms = 0;\n" ...
"    previousTarget = target;\n" ...
"else\n" ...
"    phaseTime_ms = phaseTime_ms + Ts_ms;\n" ...
"end\n" ...
"\n" ...
"if abs(target)<1e-9\n" ...
"    D = 1;\n" ...
"else\n" ...
"    D = max(0,1-k*phaseTime_ms);\n" ...
"end\n" ...
"y = x*D;\n" ...
"end\n"], Ts*1e3));

setMATLABFunctionCode(chargeBlock, sprintf([ ...
"function [qOriented_uC,qSigned_uC] = fcn(prevIout_mA,target)\n" ...
"%% Continuous signed capacitor-state proxy.\n" ...
"%% 1 mA * 1 ms = 1 uC.\n" ...
"Ts_ms = %.15g;\n" ...
"persistent qSigned\n" ...
"if isempty(qSigned)\n" ...
"    qSigned = 0;\n" ...
"end\n" ...
"\n" ...
"qSigned = qSigned + prevIout_mA*Ts_ms;\n" ...
"qSigned_uC = qSigned;\n" ...
"\n" ...
"if abs(target)<1e-9\n" ...
"    qOriented_uC = 0;\n" ...
"else\n" ...
"    qOriented_uC = max(0,sign(target)*qSigned);\n" ...
"end\n" ...
"end\n"], Ts*1e3));

setMATLABFunctionCode(complianceBlock, sprintf([ ...
"function C = fcn(q_uC,Ipp)\n" ...
"%% Current/state-dependent compliance attenuation.\n" ...
"%% Stage 6A did NOT support one universal collapse law, so retain\n" ...
"%% current-specific local Stage 5 laws at identifiable collapse currents.\n" ...
"\n" ...
"if Ipp < 17.5\n" ...
"    %% 5/10 mA no collapse; 15 mA insufficient repeated collapse evidence.\n" ...
"    C = 1;\n" ...
"elseif Ipp < 25\n" ...
"    %% 20 mA transition regime: shifted exponential.\n" ...
"    q0 = 3.9421085;\n" ...
"    k = 1.602881;\n" ...
"    C = exp(-k*max(q_uC-q0,0));\n" ...
"elseif Ipp < 40\n" ...
"    %% 30 mA strong-collapse local law.\n" ...
"    q0 = 2.5856785;\n" ...
"    s = 1.7997338;\n" ...
"    p = 5.3325528;\n" ...
"    C = exp(-(max(q_uC-q0,0)/s)^p);\n" ...
"else\n" ...
"    %% 50 mA strong-collapse local law.\n" ...
"    q0 = 0.30472454;\n" ...
"    s = 3.8163067;\n" ...
"    p = 6.0456175;\n" ...
"    C = exp(-(max(q_uC-q0,0)/s)^p);\n" ...
"end\n" ...
"\n" ...
"C = min(max(C,0),1);\n" ...
"end\n"]));

