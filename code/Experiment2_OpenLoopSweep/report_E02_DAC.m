%% Repeated-Counter visit comparisons

repeatR = struct([]);repeatR = struct( ...
    'Load_Ohm',{}, ...
    'Counter',{}, ...
    'Visits',{}, ...
    'MinMean_mA',{}, ...
    'MaxMean_mA',{}, ...
    'RangeOfVisitMeans_mA',{}, ...
    'UpMinusDown_mA',{});

for R = loads

    P = A(A.Load_Ohm==R,:);

    for code = unique(P.Counter)'

        V = P(P.Counter==code,:);

        if height(V)<2
            continue;
        end

        up = V.Mean_mA(V.Direction=="UP");
        down = V.Mean_mA(V.Direction=="DOWN");

        diffUD = NaN;

        if ~isempty(up) && ~isempty(down)
            diffUD = mean(up)-mean(down);
        end

        repeatR(end+1) = struct( ...
            'Load_Ohm',R, ...
            'Counter',code, ...
            'Visits',height(V), ...
            'MinMean_mA',min(V.Mean_mA), ...
            'MaxMean_mA',max(V.Mean_mA), ...
            'RangeOfVisitMeans_mA', ...
            max(V.Mean_mA)-min(V.Mean_mA), ...
            'UpMinusDown_mA',diffUD); %#ok<SAGROW>

    end

end

if isempty(repeatR)

    repeat = table( ...
        'Size',[0 7], ...
        'VariableTypes',{ ...
        'double','double','double','double', ...
        'double','double','double'}, ...
        'VariableNames',{ ...
        'Load_Ohm','Counter','Visits', ...
        'MinMean_mA','MaxMean_mA', ...
        'RangeOfVisitMeans_mA','UpMinusDown_mA'});

else

    repeat = struct2table(repeatR);

end

writetable(repeat,fullfile( ...
    out,'E02_RepeatedVisitComparison.csv'));

