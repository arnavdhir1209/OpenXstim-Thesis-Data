%% stage2B_build.m | Builds separate executable Stage 2B Simulink model
if ~exist('B','var'), stage2B_params; end
m=B.model;
if bdIsLoaded(m), close_system(m,0); end
if exist([m '.slx'],'file')
    error('Stage 2B model already exists. Rename/move it before rebuilding to avoid overwrite.');
end
new_system(m);
set_param(m,'SolverType','Fixed-step','Solver','FixedStepDiscrete', ...
    'FixedStep',num2str(B.Ts,17),'StopTime',num2str(B.stopTime,17), ...
    'ReturnWorkspaceOutputs','on');
% MATLAB Function block calls stage2B_step.m. Keep all five scripts on path.
blk=[m '/Burst_PI_Update'];
add_block('simulink/User-Defined Functions/MATLAB Function',blk, ...
    'Position',[340 115 610 365]);
rt=sfroot;
ch=rt.find('-isa','Stateflow.EMChart','Path',blk);
assert(~isempty(ch),'Cannot find MATLAB Function chart.');
ch.Script = sprintf([ ...
'function [I,e,ed,pTerm,xI,applied,next,clamped,frozen] = fcn(kp,ki,K,r,quantOn,deadOn,limitsOn,awOn,disturbance)\n' ...
'%%#codegen\n' ...
'persistent u x idx\n' ...
'if isempty(idx)\n' ...
'    idx = 0; u = 215; x = 0;\n' ...
'end\n' ...
'applied=u;\n' ...
'[I,e,ed,pTerm,xI,next,~,~,clamped,frozen,~] = stage2B_step( ...\n' ...
'    u,x,idx,kp,ki,K,9.593752,215,r,0.0825,21.5,322,25,0.03, ...\n' ...
'    quantOn,deadOn,limitsOn,awOn,disturbance);\n' ...
'u=next; x=xI; idx=idx+1;\n' ...
'end\n']);
% Model constants are runtime-configurable with set_param.
inputs={'Kp','Ki','Plant_gain','Reference','Enable_round', ...
    'Enable_deadband','Enable_limits','Enable_antiwindup','Disturbance'};
values=[B.Kp(1),B.Ki(1),B.K,B.r,0,0,0,0,0];
for j=1:numel(inputs)
    name=inputs{j};
    add_block('simulink/Sources/Constant',[m '/' name], ...
        'Position',[70 35+50*j 205 60+50*j], ...
        'Value',num2str(values(j),17), ...
        'SampleTime',num2str(B.Ts,17));
end
% A From Workspace disturbance allows direct step-like stress tests.
add_block('simulink/Sources/From Workspace',[m '/Disturbance_profile'], ...
    'Position',[75 575 205 615], ...
    'VariableName','B2B_disturbance', 'Interpolate','off', ...
    'OutputAfterFinalValue','Holding final value');
% Remove constant disturbance; input 9 fed from workspace.
delete_block([m '/Disturbance']);
for j=1:8
    add_line(m,[inputs{j} '/1'],['Burst_PI_Update/' num2str(j)],'autorouting','on');
end
add_line(m,'Disturbance_profile/1','Burst_PI_Update/9','autorouting','on');
outs={'current','error','adjusted_error','p_term','integral', ...
    'applied','next','clamped','integral_frozen'};
for j=1:numel(outs)
    name=['s2b_' outs{j}];
    add_block('simulink/Sinks/To Workspace',[m '/Log_' outs{j}], ...
        'Position',[750 35+62*j 920 69+62*j], ...
        'VariableName',name,'SaveFormat','Timeseries');
    add_line(m,['Burst_PI_Update/' num2str(j)], ...
        ['Log_' outs{j} '/1'],'autorouting','on');
end
try, Simulink.BlockDiagram.arrangeSystem(m); catch, end
save_system(m,fullfile(pwd,[m '.slx']));
open_system(m);
fprintf('Saved separate model %s.slx\n',m);
